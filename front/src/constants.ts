// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — معیارِ «چندمرزی بودن» تنها سدِ برابرِ زباله‌دان‌شدن است: این فایل چون فعل ندارد، مسئولیتی ندارد که خودبه‌خود مرزش را بکشد — پس مرز را باید دستی و صریح کشید. سؤالِ دروازه‌بان همیشه یکی است: «آیا این مقدار در بیش از یک‌جا و ثابت است؟» اگر نه، تبعید به محلِ مصرف. بدونِ این سؤال، فردا constants.ts می‌شود قبرستانِ هر مقداری که کسی نمی‌دانست کجا بگذارد — و آن لحظه، فایل مسئولیتش را (که «تک‌منبعِ حقیقتِ مشترک» بود) از دست داده.

// env نه این‌جا — همان تفکیکِ سیم/واژه، حالا در جنسِ ثابت: خطرناک‌ترین اشتباه، هاردکدِ API_BASE_URL یا رازها این‌جاست. ثابتِ دامنه (در هر محیط یکی) با پیکربندیِ استقرار (بینِ محیط‌ها متغیر) فرق بنیادی دارد. اولی این‌جا، دومی در env. درهم‌آمیختن‌شان یعنی build-per-env و ریسکِ لوّرفتنِ راز — دقیقاً همان مرزی که apiClient با گذاشتنِ credentials روی کوکیِ httpOnly (نه توکن در storage) رعایت کرد.

// as const — «یک حقیقت، یک نویسنده» که از cartService به ارث رسید: آن‌جا سرور تنها نویسندهٔ قیمت بود؛ این‌جا این فایل تنها نویسندهٔ این ثابت‌هاست. انجماد این یک‌طرفگی را از یک قرارداد (که می‌شود شکست) به یک تضمینِ نوعیِ کامپایلر (که نمی‌شود) ارتقا می‌دهد — و به‌علاوه literalِ دقیق (SortOrder = "asc" | "desc") می‌دهد که مستقیم به امضای سرویس‌ها وصل می‌شود.

// MIN_PASSWORD_LENGTH این‌جاست، نه فقط داخلِ validatePassword — و این ظریف است: آن 8 در validation.ts و همان 8 در پیغامِ راهنمای فرم و شاید در قاعدهٔ سرور، سه‌جا زندگی می‌کند. اگر هرکدام مستقل بنویسندش، روزی واگرا می‌شوند. پس عددِ خام از validation هم به این‌جا کوچ می‌کند و آن فایل از این‌جا واردش می‌کند — تکرارِ یک مقدار در چند مرز، دقیقاً معیارِ ورود.

// چه چیزی این‌جا نیست: پیکربندیِ محیط (env)، عددهای تک‌مصرفِ محلی (تبعید به محلِ مصرف)، پیغامِ محلی‌شده (i18n روی code، همان جدایی‌ای که validation و http رعایت کردند)، توابعِ کمکی (این فایل بی‌فعل است؛ فعل جای دیگر)، و هر مقداری که مشتق‌شدنی است (اگر از یک ثابتِ دیگر قابلِ‌محاسبه است، محاسبه‌اش کن، دوباره ننویس). این فایل فقط حقیقت‌های ثابتِ چندمرزی را یک‌بار و فقط‌خواندنی تعریف می‌کند



// دیگر تابعی در کار نیست — و این وسوسه از همه خطرناک‌تر است، چون بی‌شکل‌ترینشان است: «constants.ts؟ این که فقط یک کشوست. هر عددِ جادویی، هر رشتهٔ ثابت، هر کلیدی که یک‌جای دیگر لازم شد — بریزش این‌جا. ساختار نمی‌خواهد، تصمیم نمی‌خواهد، فقط یک انبار است.» و این کشنده‌ترین دروغِ کلِ پروژه است، چون بی‌شکلی خودش را به‌جای سادگی جا می‌زند. هر فایلِ تا این‌جا یک مسئولیتِ فعل داشت — apiClient می‌فرستاد، formatPrice تبدیل می‌کرد، validation داوری می‌کرد. constants.ts هیچ فعلی ندارد. و دقیقاً چون هیچ رفتاری ندارد که مسئولیتش را تعریف کند، تنها چیزی که از تبدیل‌شدنش به زباله‌دان جلوگیری می‌کند، یک انضباطِ صریح است — وگرنه گرانشِ «همین‌جا بریزش» هر تکه‌آشغالِ بی‌خانمانِ پروژه را به این‌جا می‌کشد.

// سه تصمیمِ بزرگ که این کشوی به‌ظاهر بی‌قاعده را از تلهٔ «انبارِ عمومی» جدا می‌کنند:

// تصمیمِ بزرگِ اول — این فایل «چرا»هاست، نه «چه»ها؛ معیارِ ورود این است: «آیا این مقدار در بیش از یک‌جا معنا دارد و ثابت است؟» یک عددِ جادویی مثلِ 86400 که فقط درونِ formatDate معنا دارد، این‌جا نمی‌آید — آن‌جا محلی می‌ماند، چون بیرونِ آن تابع بی‌معناست. ولی PAGE_SIZE = 20 که هم productService برای query می‌خواهدش، هم کامپوننتِ pagination برای شمردنِ صفحه‌ها، هم استور برای پیش‌تخصیص — این یک حقیقتِ مشترک است، و اگر در سه‌جا 20 تکرار شود، روزی یکی‌شان 25 می‌شود و آن دوتای دیگر نه. این‌جا تنها جایی است که آن 20 یک‌بار نوشته می‌شود تا سه صدازننده از یک منبع بنوشند. معیار مطلق است: تکرارِ یک مقدار در چند مرز = نامزدِ این فایل؛ مقدارِ محلیِ یک تابع = تبعیدِ به همان تابع. همان درسِ formatterFor که هزینه را از حلقهٔ داغ بیرون کشید — این‌بار تعریف را از تکرار بیرون می‌کشم.

// تصمیمِ بزرگِ دوم — مرزِ خطرناک: ثابتِ زمانِ-ساخت این‌جاست، پیکربندیِ زمانِ-اجرا نه؛ و این همان شکافِ apiClient/http است در محورِ داده. وسوسه این است که API_BASE_URL را هم این‌جا بگذارم — بالاخره «ثابت» است دیگر. ولی نه: آدرسِ سرور بینِ dev و staging و prod فرق می‌کند، پس یک پیکربندیِ زمانِ-اجراست که از env می‌آید، نه یک ثابتِ بیک‌شده در باندل. اگر این‌جا هاردکد می‌شد، برای هر محیط یک build جدا لازم بود و یک روز کلیدِ prod در باندلِ dev لو می‌رفت. قاعده تیز است: اگر مقدار بینِ محیط‌ها عوض می‌شود یا راز است → env؛ اگر یک حقیقتِ ثابتِ دامنه است که در هر محیط یکی است (PAGE_SIZE, MAX_CART_QTY, کلیدهای localStorage) → این‌جا. همان تفکیکِ «سیم در برابر واژه» که در apiClient کشیدم، حالا در جنسِ داده: چیزِ متغیر بیرون، چیزِ ثابت درون.

// تصمیمِ بزرگِ سوم — as const و انجماد، چون این فایل تنها جایی است که یک نوشتنِ ناخواسته می‌تواند همه‌جا را مسموم کند. یک ثابت که کلِ پروژه از آن می‌خواند، اگر جایی سهواً mutate شود، باگی می‌سازد که ردش غیرممکن است — چون منبع یکی است ولی خرابکار ناشناس. پس هر شیِ ثابت as const می‌گیرد تا هم literalش دقیق شود (نوعِ "asc" | "desc" نه string)، هم فقط‌خواندنی شود. این دقیقاً همان فلسفهٔ «منبعِ حقیقتِ واحد» است که cartService با setCart(res.data) رعایت کرد: یک حقیقت، یک نویسنده. آن‌جا نویسنده سرور بود و کلاینت فقط می‌نشاند؛ این‌جا نویسنده همین فایل است و بقیهٔ پروژه فقط می‌خواند. انجماد، این یک‌طرفگی را از قرارداد به تضمینِ نوعی ارتقا می‌دهد.

// و این ایستگاه، جدول را حولِ محوری می‌چرخاند که در هیچ ردیفِ قبل ستون نبود، چون همهٔ فایل‌های قبلی داشتندش: فعل. از apiClient تا validation، هر فایل یک رفتار بود — چیزی که اجرا می‌شد. constants.ts اولین فایلی است که اجرا نمی‌شود؛ فقط هست:

// فایل‌های تا این‌جا (هسته + util)	constants.ts
// فعل دارد؟	بله (می‌فرستد/تبدیل/داوری)	نه — فقط هست
// ورودی/خروجی؟	دارد	هیچ‌کدام
// مرزش را چه می‌کشد؟	مسئولیتِ رفتاری	انضباطِ صریحِ «چندمرزی؟»
// منبعِ باگ	اجرا (مرز، زمان، خود)	تکرار / mutate / نشتِ env
// نویسنده	متغیر (سرور، کاربر)	فقط خودش (as const)



// کتهٔ ظریفِ این ایستگاه این است: فایلی که هیچ کاری نمی‌کند، سخت‌ترین فایل برای انضباط است — دقیقاً چون رفتاری ندارد که مرزش را خودکار تعریف کند. apiClient نمی‌توانست زباله‌دان شود چون هر خطِ اضافه‌اش باید کار می‌کرد؛ constants.ts می‌تواند بی‌صدا بپوسد چون پذیرفتنِ یک آشغالِ بی‌فعل هیچ اصطکاکی ندارد. همان درسِ کلِ پروژه، در وارونه‌ترین شکلش: جایی که مسئولیت خودش را تحمیل نمی‌کند، باید دستی تحمیلش کنی — وگرنه بی‌شکلی، خودش را جای سادگی جا می‌زند و کشو پر از حقیقت‌های بی‌صاحب می‌شود. 