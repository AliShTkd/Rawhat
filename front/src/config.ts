

// src/config.ts

/**
 * config = تبعیدگاهِ آن‌چه constants بیرون گذاشت: مقادیرِ محیط‌متغیر و رازها.
 * شبیهِ constants است ولی قرینه‌اش:
 *   constants → نویسنده خودش (مورد‌اعتماد)، مقدار زمانِ-ساخت، as const نوعی.
 *   config    → نویسنده «محیط» (بی‌اعتماد)، مقدار زمانِ-اجرا، مرزِ ورود مثلِ validation.
 * سه اصل:
 *   - env بی‌اعتماد است: پارس و اعتبارسنجی، و شکستِ بلند — ولی یک‌بار، در بوت.
 *   - مرزِ راز: فقط VITE_* به باندل می‌رسد؛ رازِ واقعی هرگز (مثلِ کوکیِ httpOnly).
 *   - یک‌بار پارس، منجمد، تایپ‌شده: کیسهٔ رشته‌ایِ خام → شیِ شکل‌دارِ فقط‌خواندنی.
 */

// خواننده‌های کوچک که «نه»ِ بلند می‌زنند — قرینهٔ fail() در validation، ولی در بوت.
function required(key: string): string {
  const v = import.meta.env[key];
  if (v == null || v === "") {
    // بلند و در ثانیهٔ صفر — نه undefined خاموشی که دقیقهٔ چهلم می‌ترکد.
    throw new Error(`[config] متغیرِ محیطیِ الزامی غایب است: ${key}`);
  }
  return v;
}

function asInt(key: string, fallback: number): number {
  const raw = import.meta.env[key];
  if (raw == null || raw === "") return fallback;
  const n = Number(raw);
  if (!Number.isFinite(n)) throw new Error(`[config] ${key} باید عدد باشد، بود: "${raw}"`);
  return n;
}

function asBool(key: string, fallback: boolean): boolean {
  const raw = import.meta.env[key];
  if (raw == null || raw === "") return fallback;
  return raw === "true" || raw === "1";
}

/**
 * پارسِ یک‌بارهٔ کلِ محیط. اگر چیزی خراب باشد، همین‌جا (بارگذاریِ ماژول = بوت)
 * می‌ترکد — پیش از رندرِ اولین پیکسل. هیچ مصرف‌کننده‌ای undefined نمی‌بیند.
 */
export const config = Object.freeze({
  // ── شبکه: آدرسِ سرور، محیط‌متغیر، پس این‌جا نه در constants ──
  apiBaseUrl: required("VITE_API_BASE_URL"),
  apiTimeoutMs: asInt("VITE_API_TIMEOUT_MS", 15_000),

  // ── محیط: dev/staging/prod را می‌شناسد؛ رفتارِ لاگ و خطا از این می‌آید ──
  mode: import.meta.env.MODE as "development" | "production" | "test",
  isProd: import.meta.env.PROD,
  enableAnalytics: asBool("VITE_ENABLE_ANALYTICS", false),

  // ── رازهای *عمومی* — امن برای باندل، چون VITE_ و از جنسِ کلیدِ عمومی ──
  stripePublicKey: required("VITE_STRIPE_PUBLIC_KEY"),
  //  توجه: VITE_STRIPE_SECRET_KEY وجود ندارد و نباید داشته باشد —
  //  رازِ واقعی فقط در سرور نفس می‌کشد (همان مرزِ کوکیِ httpOnly در apiClient).
} as const);

export type Config = typeof config;





















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — env ورودیِ بی‌اعتماد است، پس config مرزِ ورود است نه کشوی ثابت: این تفاوتِ کلِ فایل با constants است. constants مقدارش را می‌نوشت و می‌شد به آن اعتماد کرد؛ config مقدارش را از محیطِ استقرار می‌گیرد و نمی‌شود. پس همان درسِ validation این‌جا هم صادق است — «به ورودی اعتماد نکن، داوری‌اش کن، بلند رد کن» — فقط این‌بار ورودی از سمتِ عملیات/استقرار می‌آید، نه کاربر. و چون env فقط در بوت تغییر می‌کند، داوری یک‌بار در بارگذاریِ ماژول رخ می‌دهد (درسِ formatterFor: هزینه از حلقهٔ داغ بیرون).

// شکست در بوت، نه در دقیقهٔ چهلم — «زودترین لحظه» فلسفهٔ کلِ فایل است: بدترین حالتِ یک envِ غلط، undefinedی خاموش است که تا اولین fetch زنده می‌ماند و بعد با خطای مبهم می‌ترکد. required() این را وارونه می‌کند: اگر متغیری غایب است، برنامه پیش از رندر می‌میرد با پیغامی که دقیقاً کدام کلید را نام می‌برد. این همان «سقوطِ نرم نداریم؛ نه‌گفتن کارِ اصلی است»ِ validation است، منتقل به لحظهٔ بوت.

// مرزِ VITE_ یک دیوارِ امنیتی است، نه قرارداد — همان درسِ کوکیِ httpOnly: هرچه پیشوندِ VITE_ بگیرد، در باندل برای هر کاربر قابل‌دیدن است. پس رازِ واقعی (کلیدِ مخفیِ استرایپ، توکنِ سرویس) هرگز این‌جا نمی‌آید — عیناً همان‌طور که apiClient توکن را در کوکیِ httpOnly گذاشت نه localStorage. اینکه configِ کلاینت رازِ سرور را نمی‌داند، یک ضعف نیست؛ یک تصمیمِ امنیتیِ فعال است.

// یک‌بار پارس، تایپ‌شده بیرون بده — تا مصرف‌کننده‌ها undefined-چکِ تکراری نکنند: import.meta.env کیسهٔ رشته‌ایِ شاید-غایب است. اگر خام پخش شود، هر مصرف‌کننده باید دوباره تبدیل و چک کند — همان واگراییِ تکراری که constants دفع کرد. پس این‌جا یک‌بار به Configِ تایپ‌شده و منجمد تبدیل می‌شود: apiTimeoutMs یک numberِ واقعی است، نه "15000" | undefined. apiClient مستقیم config.apiTimeoutMs را می‌خورد، بی‌هیچ نگرانی.

// چه چیزی این‌جا نیست: ثابتِ دامنه‌ایِ محیط‌ثابت (PAGE_SIZE, ROUTES → constants، چون در هر محیط یکی‌اند)، رازِ سمتِ سرور (فقط سرور، هرگز باندل)، منطق یا فعل (این فایل هم بی‌فعل است، فقط پارس می‌کند و می‌ایستد)، و مقادیرِ مشتق‌شدنی (اگر از mode قابل‌محاسبه است، محاسبه، نه env جدا). این فایل فقط کیسهٔ خامِ بی‌اعتمادِ env را یک‌بار به یک پیکربندیِ تایپ‌شده، اعتبارسنجی‌شده و منجمد تبدیل می‌کند، و اگر محیط خراب بود، در ثانیهٔ صفر بلند می‌میرد.





// دومین فایلِ بی‌فعل — و این‌جا تله از همه ظریف‌تر است، چون config.ts شبیه‌ترین چیز به constants.ts است و درست به همین دلیل قرینهٔ خطرناکِ آن. یادت هست در constants چه چیزی را با انگشت بیرون گذاشتم؟ «API_BASE_URL, رازها, کلیدِ استرایپ → env، نه این‌جا.» خب، config.ts دقیقاً همان تبعیدگاه است — جایی که آن مقادیرِ محیط‌متغیر فرود می‌آیند. و وسوسه این است: «این هم که یک کشوی دیگرِ ثابت‌هاست، مثلِ constants؛ فقط این‌بار مقدارها از process.env می‌آیند. همان as const، همان انجماد، تمام.» و این کشنده است، چون یک تفاوتِ بنیادی را می‌پوشاند: constants مقدارهایش را خودش می‌نوشت — نویسنده‌اش مورد‌اعتماد بود (همین فایل). config مقدارهایش را از بیرون می‌گیرد — و بیرون، مورد‌اعتماد نیست. یک متغیرِ محیطی می‌تواند غایب باشد، غلط‌تایپ‌شده باشد، رشتهٔ "undefined" باشد، یا در prod فراموش شده باشد. config.ts یک کشوی ثابت نیست؛ یک مرزِ ورود است — درست مثلِ validation، ولی این‌بار ورودیِ بی‌اعتماد از سمتِ محیطِ استقرار می‌آید، نه از سمتِ کاربر.

// سه تصمیمِ بزرگ که این دوقلوی ظاهریِ constants را قرینه می‌کنند:

// تصمیمِ بزرگِ اول — env ورودیِ بی‌اعتماد است، پس اعتبارسنجی می‌شود و بلند می‌ترکد؛ ولی یک‌بار، در بوت — نه در حلقهٔ داغ. این دقیقاً همان فلسفهٔ validation است، با دو چرخش. اول: مثلِ validation، اعتبارسنجیِ خاموش گناه است — اگر API_BASE_URL غایب باشد و بی‌سروصدا undefined بماند، برنامه ساعت‌ها بعد با یک fetchِ به "undefined/products" می‌ترکد و ردش غیرممکن است. پس مثلِ validation بلند «نه» می‌گویم. ولی چرخشِ دوم، درسِ formatterFor است: هزینه را از حلقهٔ داغ بیرون بکش. validation در هر کیبردزدن داوری می‌کرد چون ورودی‌اش زنده بود؛ ولی env فقط یک‌بار در لحظهٔ بوت تغییر می‌کند. پس اعتبارسنجی یک‌بار در بارگذاریِ ماژول رخ می‌دهد و اگر خراب بود، برنامه همان‌جا، پیش از رندرِ اولین پیکسل می‌میرد — نه دیرتر. «در مرز بترس»، ولی ترس را به زودترین لحظه ببر: یک پیکربندیِ غلط باید در ثانیهٔ صفرِ بوت داد بزند، نه در دقیقهٔ چهلمِ کاربر.

// تصمیمِ بزرگِ دوم — مرزِ راز: چه چیزی به باندلِ مرورگر می‌رسد و چه چیزی هرگز. این عیناً همان تصمیمِ کوکیِ httpOnly در apiClient است. خطرناک‌ترین خطِ این فایل نامرئی است: تفکیکِ «امن برای فرستادن به مرورگر» از «فقط سرور». در Vite هر متغیری با پیشوندِ VITE_ به باندلِ کلاینت تزریق می‌شود — یعنی هر کاربری می‌تواند در DevTools ببیندش. پس این پیشوند یک مرزِ امنیتیِ تمام‌عیار است، نه یک قرارداد نام‌گذاری. کلیدِ عمومیِ استرایپ؟ VITE_، امن. کلیدِ مخفیِ استرایپ؟ هرگز نه — آن فقط در سرور نفس می‌کشد. این همان یک‌طرگیِ apiClient است که توکن را در کوکیِ httpOnly گذاشت نه در localStorage: رازِ واقعی هرگز به دستِ جاوااسکریپتِ مرورگر نمی‌رسد. config.tsِ سمتِ کلاینت عمداً فقط چیزهای عمومی را می‌شناسد؛ اینکه چیزی را نمی‌داند، خودش یک تصمیمِ امنیتی است.

// تصمیمِ بزرگِ سوم — یک‌بار پارس کن، منجمد کن، تایپ‌شده بیرون بده: از رشتهٔ خامِ بی‌شکلِ env به یک شیِ شکل‌دارِ فقط‌خواندنی. process.env/import.meta.env یک کیسهٔ Record<string, string | undefined> است — همه‌چیز رشته، همه‌چیز شاید-غایب. اگر کلِ برنامه مستقیم از این کیسه بخواند، هر مصرف‌کننده باید دوباره undefined را چک کند، "true" را به boolean تبدیل کند، "20" را عدد کند. این همان تکراری است که constants با MIN_PASSWORD_LENGTH دفع کرد. پس این‌جا یک‌بار پارس می‌شود: رشته به عددِ واقعی، "true" به boolean، غایب به خطای بوت. خروجی یک شیِ منجمدِ تایپ‌شده است — همان «یک حقیقت، یک نویسنده» که constants با as const ساخت، ولی چون مقدار زمانِ-اجرا می‌آید، انجماد هم زمانِ-اجراست (Object.freeze)، نه صرفاً نوعی.



// و این ایستگاه، جدول را حولِ محوری می‌چرخاند که constants پنهانش کرده بود، چون هر دو فایل بی‌فعل و ثابت‌نما هستند و به‌ظاهر یکی: منشأ و اعتمادِ مقدار. constants و config دوقلوهای آینه‌ای‌اند — یکی مقدارش را از درون می‌نویسد و به آن اعتماد دارد، دیگری از بیرون می‌گیرد و نباید اعتماد کند:

// constants.ts	config.ts
// منشأ مقدار	خودِ فایل می‌نویسد	محیط (env) می‌دهد
// اعتماد	مورد‌اعتماد (درونی)	بی‌اعتماد (بیرونی)
// زمانِ مقدار	زمانِ-ساخت (بیک در باندل)	زمانِ-اجرا (بوت)
// رفتار با خرابی	ممکن نیست (خودت نوشتی)	شکستِ بلند در بوت (مثلِ validation)
// انجماد	as const (نوعی)	Object.freeze (زمانِ-اجرا) + نوعی
// مرزِ راز	توکن عمداً نیست	VITE_ = دیوار؛ رازِ واقعی هرگز
// خویشاوندِ پنهان	کشوی ثابت	مرزِ ورود — خواهرِ validation



// نکتهٔ ظریفِ این ایستگاه این است: config.ts در پوشه و ظاهر، دوقلوی constants.ts است — هر دو بی‌فعل، هر دو فقط‌خواندنی، هر دو «کشوی مقدار». ولی خویشاوندیِ واقعیاش با validation.ts است که آن‌سوی پروژه نشسته — چون هر دو مرزِ ورودِ دادهٔ بی‌اعتماداند، فقط منبعِ بی‌اعتماد فرق دارد: validation به کاربر مشکوک است، config به محیطِ استقرار. همان درسِ اولِ کلِ پروژه، حالا در جایی که بیش از همه فریب می‌دهد: همسایگیِ ظاهری و پوشه‌ای دوباره دروغ گفت — config کنارِ constants می‌نشیند ولی هم‌خونِ validation است؛ چون خویشاوندی را نه شکلِ فایل و نه محلِ سکونتش، که جهتِ اعتماد به داده تعیین می‌کند. 