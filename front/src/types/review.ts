
// src/types/review.ts
import type { Paginated } from "./product";

/** امتیاز — عددِ صحیحِ محدود، نه `number`ِ باز. ستارهٔ ۰ یا ۶ بی‌معناست. */
export type Rating = 1 | 2 | 3 | 4 | 5;

/**
 * وضعیتِ بازبینیِ نظر — نظرِ تازه پیش از نمایشِ عمومی تأیید می‌شود.
 * UIِ «نظرِ شما ثبت شد و در انتظارِ تأیید است» از این می‌آید.
 */
export type ReviewStatus = "pending" | "approved" | "rejected";

/**
 * نویسندهٔ نظر — ارجاعِ سبک و عمومی، بدونِ دادهٔ حساس.
 * همان انضباطِ `User`: نه ایمیل، نه نقش؛ فقط چیزی که کنارِ نظر نشان داده می‌شود.
 */
export interface ReviewAuthor {
  id: string;
  /** نامِ نمایشی؛ ممکن است «کاربرِ ثبت‌شده» یا نامِ کوتاه باشد. */
  name: string;
  avatarUrl?: string;
}

/**
 * یک نظرِ کاربر روی محصول — شکلی که سرور برمی‌گرداند و UI می‌خواند.
 */
export interface Review {
  id: string;
  productId: string;

  author: ReviewAuthor;
  rating: Rating;

  /** عنوانِ کوتاهِ اختیاری، مثل «کیفیتِ عالی». */
  title?: string;
  body: string;

  /**
   * خریدِ تأییدشده — نشانِ «خریدِ ثبت‌شده» کنارِ نظر.
   * اعتمادِ بیشتر به نظری که از خریدِ واقعی آمده.
   */
  verifiedPurchase: boolean;

  /** رأی‌های «این نظر مفید بود». */
  helpfulCount: number;
  /** آیا کاربرِ فعلی این نظر را مفید علامت زده — برای حالتِ دکمه. */
  markedHelpful?: boolean;

  status: ReviewStatus;
  createdAt: string;
}

/** یک صفحهٔ نتیجهٔ نظر — همان الگوی `Paginated`. */
export type ReviewPage = Paginated<Review>;

/**
 * خلاصهٔ آماریِ امتیازها — مستقل از فهرستِ نظرها.
 * صفحهٔ محصول این را برای هدرِ «۴٫۶ از ۵» بدونِ کشیدنِ خودِ نظرها می‌خواهد.
 */
export interface RatingSummary {
  /** میانگینِ امتیاز؛ اعشاری مثل ۴٫۶. */
  average: number;
  /** تعدادِ کلِ نظرها. */
  total: number;
  /**
   * توزیعِ ستاره‌ها: چند نظر برای هر امتیاز.
   * برای نمودارِ میله‌ایِ «۵ ستاره: ۱۲۰».
   */
  distribution: Record<Rating, number>;
}

/**
 * ورودیِ فرمِ ثبتِ نظر — قراردادِ `services/reviews.create`.
 * فقط چیزی که کاربر می‌فرستد؛ id/تاریخ/وضعیت را سرور می‌سازد.
 */
export interface CreateReviewInput {
  productId: string;
  rating: Rating;
  title?: string;
  body: string;
}

/** مرتب‌سازیِ فهرستِ نظرها — برای دراپ‌داونِ «مرتب‌سازی بر اساس». */
export type ReviewSort = "newest" | "highest" | "lowest" | "most_helpful";












// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — RatingSummary مستقل از Review[]: این ظریف‌ترین انتخابِ این فایل است. وسوسه بود که میانگین را از روی آرایهٔ نظرها حساب کنم. ولی صفحهٔ محصول باید «۴٫۶ از ۵ (۲۳۰ نظر)» را در هدر نشان دهد بدونِ واکشیِ ۲۳۰ نظر — و توزیعِ ستاره‌ها هم روی کلِ نظرهاست، نه فقط صفحهٔ اولِ قابل‌مشاهده. پس خلاصه یک endpointِ جدا و یک تایپِ جدا است. این دقیقاً همان الگوی «سبک برای بالای صفحه، سنگین برای فهرست» است که در محصول/سفارش/دسته دیدیم، فقط این‌بار به‌شکلِ «آمار در برابرِ ردیف‌ها».

// Rating = 1|2|3|4|5 به‌جای number (تصمیمِ کوچکِ ارزشمند): با union literal، هم ستارهٔ نامعتبر در زمانِ کامپایل رد می‌شود، و هم distribution: Record<Rating, number> دقیقاً پنج کلید را تضمین می‌کند — نه کم، نه زیاد. اگر number بود، distribution می‌توانست کلیدِ ۷ داشته باشد یا کلیدِ ۳ را جا بیندازد. تایپ این‌جا دارد یک قانونِ دامنه را اجرا می‌کند، نه فقط شکل را.

// CreateReviewInput جدا از Review — اولین تفکیکِ خواندن/نوشتن: تا الان بیشتر تایپ‌هایمان خواندنی بودند. نظر اولین دامنه‌ای است که کاربر می‌نویسد، پس فرم فقط چهار فیلد می‌فرستد (productId, rating, title?, body) و سرور بقیه را می‌سازد (id, author, تاریخ, verifiedPurchase, status). اگر یک تایپ برای هر دو کار می‌کردم، فرم مجبور می‌شد فیلدهایی را که نمی‌داند (مثلِ helpfulCount) اختیاری یا جعلی پر کند. این همان الگویی است که در cart با AddToCartInput و در user با RegisterInput شروع شد.

// verifiedPurchase و status — دو نشانِ اعتماد: اولی می‌گوید «این کاربر واقعاً خریده»، دومی جریانِ «ثبت شد، منتظرِ تأیید» را ممکن می‌کند. هر دو دادهٔ سروری‌اند و کاربر نمی‌فرستدشان — برای همین در Review هستند ولی در CreateReviewInput نیستند.

// چه چیزی این‌جا نیست (عمدی): fetchReviews/createReview/markHelpful (کارِ services/reviews)، محاسبهٔ میانگین (کارِ سرور، نه کلاینت)، و ارجاعِ نظر به Product (یعنی فیلدِ rating?: RatingSummary روی Product) — که این آخری باز هم یک الحاقِ پیشنهادی به product.ts است، درست مثلِ brand.


// رسیدیم به types/review.ts — و این هفتمین تکهٔ لایهٔ تایپ است، ولی جنسش کمی فرق دارد: تا الان بیشتر تایپ‌ها داده‌ی خواندنی بودند (محصول، دسته، برند را نمایش می‌دهی)؛ نظر اولین دامنه‌ای است که سنگینی‌اش روی نوشتنِ کاربر است — کاربر نظر می‌سازد، امتیاز می‌دهد، رأیِ «مفید بود» ثبت می‌کند. پس این‌جا برای اولین بار تفکیکِ «شکلِ خواندن» از «شکلِ ارسالِ فرم» جدی می‌شود.

// فرض‌های مهم:

// نظر روی محصول می‌نشیند و به کاربر بند است: پس هم productId و هم یک ارجاعِ سبکِ نویسنده دارد — ولی بدونِ ایمیل/دادهٔ حساس، دقیقاً همان انضباطِ User که توکن را بیرون گذاشت. فقط نامِ نمایشی و آواتار.
// امتیاز عددِ محدودِ ۱ تا ۵ است: یک type Rating = 1|2|3|4|5 صریح، نه numberِ باز — تا ستاره‌ی ۷ یا ۰ اصلاً بی‌معنا باشد در سطحِ تایپ.
// الگوی «سبک/سنگین» این‌بار به‌شکلِ «خلاصهٔ آماری در برابرِ تک‌نظر»: صفحهٔ محصول یک RatingSummary می‌خواهد (میانگین + توزیعِ ستاره‌ها) که مستقل از فهرستِ Reviewهاست — چون هدرِ «۴٫۶ از ۵ (۲۳۰ نظر)» را بدونِ کشیدنِ خودِ نظرها باید نشان دهی.
// شکلِ ارسال جدا از شکلِ نمایش: CreateReviewInput فقط چیزی است که فرم می‌فرستد؛ Review چیزی است که سرور برمی‌گرداند (با id, تاریخ, وضعیتِ تأیید).
// ts



// خب، این فایل همان هشدارِ پیامِ قبل را پررنگ‌تر کرد: الحاق‌های معلق به product.ts دارند دو تا می‌شوند. حالا product.ts دو چیزِ کم دارد که فایل‌های بعدی طلبش کرده‌اند:

// الحاقِ معلق	از کجا آمد	چه چیزی را زنده می‌کند
// brand?: BrandRef	brand.ts	برند روی کارتِ محصول و فیلتر
// rating?: RatingSummary	review.ts	ستاره‌ها روی کارت و هدرِ محصول
// این دیگر یک نکتهٔ فرعی نیست؛ یک الگو شد. و صادقانه بگویم: هرچه بیشتر تایپِ جانبی اضافه کنیم، این فهرست بلندتر می‌شود و product.ts بیشتر از واقعیت عقب می‌ماند. فکر می‌کنم رسیده‌ایم به همان نقطه‌ای که در پیامِ قبل پیش‌بینی کردم: وقتِ یک بازنگریِ کوتاهِ product.ts است تا این دو الحاق رسمی شوند و بدهی پیش از انباشته‌شدن بسته شود.

// پیشنهادِ مشخصم:

// بازنگریِ product.ts (پیشنهادِ اول) — brand?: BrandRef و rating?: RatingSummary را رسمی کن. کوچک، تمیزکننده، و جلوی رشدِ بدهی را می‌گیرد. ProductWithBrandِ موقتیِ فایلِ برند هم بعدش حذف می‌شود.
// utils/money.ts — هنوز پرمصرف‌ترین تکهٔ اجراشونده.
