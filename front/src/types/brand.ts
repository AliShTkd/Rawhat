
// src/types/brand.ts
import type { ProductImage, Paginated, Product } from "./product";

/**
 * ارجاعِ سبکِ برند — قرینهٔ `CategoryRef`.
 * همانی که کارتِ محصول و چیپِ فیلتر مصرف می‌کنند.
 */
export interface BrandRef {
  id: string;
  name: string;
  slug: string;
  /** لوگوی اختیاری برای نمایش در کارت/فیلتر. */
  logoUrl?: string;
}

/**
 * برندِ کامل به شکلِ صاف — برخلافِ دسته، سلسله‌مراتب ندارد.
 * برای فهرستِ برندها و منوی برند.
 */
export interface Brand extends BrandRef {
  /** تعدادِ محصولاتِ این برند — برای «(۸۷)» کنارِ نام. */
  productCount?: number;
  /** حرفِ اولِ الفبا برای گروه‌بندیِ فهرستِ A–Z / آ–ی. */
  initial?: string;
  /** برندِ برجسته؛ برای بخشِ «برندهای منتخب». */
  featured?: boolean;
}

/**
 * شکلِ کاملِ صفحهٔ برند — توضیح، بنر و متادیتای سئو.
 * `Brand.tsx` این را برای هدرِ صفحه مصرف می‌کند.
 */
export interface BrandDetail extends Brand {
  description?: string;
  /** بنرِ بالای صفحهٔ برند. */
  banner?: ProductImage;
  seoTitle?: string;
  seoDescription?: string;
}

/** یک صفحهٔ نتیجهٔ برند — همان الگوی `Paginated`. */
export type BrandPage = Paginated<Brand>;

/**
 * الحاقِ پیشنهادی برای `Product` — این‌جا فقط مستند می‌شود.
 * وقتی `product.ts` را بازکردیم، این فیلد اضافه شود:
 *   interface Product { brand?: BrandRef; }
 * تا کارت و فیلتر بتوانند برند را نشان دهند.
 */
export type ProductWithBrand = Product & { brand?: BrandRef };















// نکاتِ مهمِ کوتاه:

// مهم‌ترین نکته — یک بدهیِ کوچک در product.ts پیدا شد: برای اینکه کارتِ محصول برند را نشان دهد، Product باید یک brand?: BrandRef داشته باشد. چون تایپِ محصول را چند فایل پیش قفل کردیم و صفحه‌ها ممکن است شروع به مصرفش کرده باشند، خاموش تغییرش نمی‌دهم. دو راه گذاشتم: یا در بازنگریِ بعدیِ product.ts فیلدِ brand?: BrandRef را رسماً اضافه کنیم (راهِ تمیز)، یا موقتاً از ProductWithBrand استفاده شود. پیشنهادِ صادقانه‌ام راهِ اول است؛ ProductWithBrand فقط پلی است تا مجبور نباشی همین حالا product.ts را بازکنی.

// برند صاف است، دسته درختی — تفاوتِ ساختاریِ آگاهانه: وسوسه بود که برند را هم مثلِ category با parentId بسازم «برای قرینگی». نکردم، چون برند واقعاً سلسله‌مراتب ندارد (اپل زیرمجموعهٔ چیزی نیست). مدل‌کردنِ چیزی که وجود ندارد فقط پیچیدگیِ بی‌مصرف می‌آورد. initial را به‌جایش گذاشتم چون فهرستِ واقعیِ برندها معمولاً الفبایی گروه‌بندی می‌شود، نه درختی.

// BrandRef جدا از Brand: همان تفکیکِ CategoryRef/Category. کارتِ محصول فقط BrandRefِ سه‌فیلدی می‌خواهد، نه productCount/featured. تایپِ سبک را جایی می‌گذارم که مصرفش سبک است.

// چه چیزی این‌جا نیست (عمدی): fetchBrands/fetchBrand (کارِ services/brands)، گروه‌بندیِ الفبایی (تابعِ utils)، و فیلترِ «محصولاتِ این برند» (که به پارامترهای مشترکِ Search/Category تعلق دارد). فقط شکلِ خودِ برند.



// رسیدیم به types/brand.ts — و این باز هم یک تکملهٔ درست است، از همان جنسِ category. برند و دسته دو محورِ موازیِ ناوبری‌اند: کاربر یا با «لپ‌تاپ» (دسته) می‌گردد یا با «اپل» (برند). در product.ts برای دسته یک CategoryRefِ سبک گذاشتم ولی برند را جا انداختم — فقط یک رشتهٔ نام بود یا اصلاً نبود. این فایل آن شکاف را می‌بندد و یک نکتهٔ ظریف را هم مجبورمان می‌کند حل کنیم: Product باید به برند هم ارجاع بدهد.

// فرض‌های مهم:

// BrandRefِ سبک، دقیقاً مثلِ CategoryRef: همان چیزی که کارتِ محصول و فیلترها لازم دارند — id, name, slug, و شاید لوگو. این باید به Product اضافه شود (فیلدِ brand?)، ولی چون تایپِ محصول قبلاً قفل شده، این را به‌عنوان الحاقِ پیشنهادی علامت می‌زنم نه تغییرِ خاموش.
// الگوی «سبک/سنگین» را ادامه می‌دهم: Brand (منو/فیلتر) در برابرِ BrandDetail (صفحهٔ برند با توضیح و بنر) — همان انضباطی که در هر چهار فایلِ قبل تکرار شد.
// برند صاف است، نه درختی: برخلافِ category، برند سلسله‌مراتب ندارد؛ پس نه parentId و نه children. این تفاوتِ ساختاریِ مهمی است که مدل را ساده‌تر نگه می‌دارد.
// ts


// خب، لایهٔ تایپ حالا شش‌تایی شد و دو محورِ ناوبری (دسته و برند) قرینه‌اند:

