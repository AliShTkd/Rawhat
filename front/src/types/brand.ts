// ولی این فایل یک چیزِ کوچک را روشن کرد که ارزشِ گفتن دارد: brand.ts اولین فایلی بود که یک بدهیِ واقعی به یک فایلِ قبلی برگرداند — آن brand?: BrandRef که product.ts کم دارد. این طبیعی است و بد نیست؛ نشانهٔ این است که تایپ‌ها دارند با هم حرف می‌زنند. ولی یک هشدارِ کوچک هم هست: اگر همین‌طور فایلِ تایپِ جدید اضافه کنیم، این «الحاق‌های معلق» جمع می‌شوند. شاید بعد از یکی‌دو تایپِ دیگر، یک بازنگریِ کوتاهِ product.ts لازم شود تا brand (و هر الحاقِ دیگر) رسمی شوند.

// مسیرهای بعدی، حالا با یک گزینهٔ تازه:

