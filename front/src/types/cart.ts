
// src/types/cart.ts
import type { Money, Product } from "./product";

/**
 * یک قلم در سبد.
 * عکسِ فوریِ سبک از محصول را نگه می‌دارد تا سبد بدونِ fetchِ دوباره رندر شود،
 * ولی `unitPrice` در لحظهٔ افزودن قفل می‌شود (سرور موقعِ checkout بازاعتبارسنجی می‌کند).
 */
export interface CartItem {
  /** شناسهٔ محصول — کلیدِ یکتا برای به‌روزرسانی/حذف. */
  productId: string;
  /** برای لینکِ سبد به صفحهٔ محصول. */
  slug: string;

  /** عکسِ فوریِ نمایشی؛ عمداً تکرارِ داده، تا سبد خودکفا باشد. */
  title: string;
  image: Product["image"];

  /** قیمتِ واحد در لحظهٔ افزودن به سبد. */
  unitPrice: Money;
  /**
   * قیمتِ پیش از تخفیفِ همان لحظه، اگر بود؛ برای نمایشِ خط‌خوردهٔ سبد.
   */
  compareAtUnitPrice?: Money;

  /** تعداد؛ همیشه integer و ≥ ۱. صفر یعنی باید حذف شود. */
  quantity: number;

  /**
   * سقفِ قابلِ‌سفارش در لحظهٔ افزودن (از `stockCount`)، اگر معلوم بود.
   * UI برای جلوگیری از افزایشِ بیش از موجودی استفاده می‌کند.
   */
  maxQuantity?: number;
}

/**
 * جمع‌های مشتق‌شدهٔ سبد — *ذخیره نمی‌شوند*، بلکه از روی آیتم‌ها محاسبه می‌شوند.
 * این فقط شکلِ خروجیِ آن محاسبهٔ خالص است.
 */
export interface CartTotals {
  /** جمعِ `unitPrice × quantity` روی همهٔ اقلام. */
  subtotal: Money;
  /** مجموعِ صرفه‌جویی از تخفیف‌ها (اختلافِ compareAt با قیمت). */
  discount: Money;
  /** تعدادِ کلِ اقلام (جمعِ quantityها) — برای نشانگرِ آیکونِ سبد. */
  itemCount: number;
  /**
   * مبلغِ نهاییِ سمتِ کلاینت. هزینهٔ ارسال/مالیات عمداً این‌جا نیست،
   * چون آن‌ها را فقط سرور در `checkout` قطعی می‌کند.
   */
  total: Money;
}

/**
 * کلِ حالتِ سبد — همانی که `stores/cart` نگه می‌دارد و
 * `Cart`/`Checkout`/نشانگرِ هدر مصرفش می‌کنند.
 */
export interface Cart {
  items: ReadonlyArray<CartItem>;
  /** ارزِ سبد؛ همهٔ اقلام باید هم‌ارز باشند. */
  currency: Money["currency"];
  /**
   * زمانِ آخرین تغییر (ISO) — برای ادغامِ سبدِ مهمان با سرور
   * پس از ورود، و رفعِ تعارض.
   */
  updatedAt: string;
}

/** ورودیِ استانداردِ افزودن به سبد — از صفحهٔ محصول یا کارت. */
export interface AddToCartInput {
  product: Product;
  quantity: number;
}

/** سبدِ خالیِ اولیه — نقطهٔ شروعِ store. */
export const EMPTY_CART: Cart = {
  items: [],
  currency: "IRR",
  updatedAt: new Date(0).toISOString(),
};













// نکاتِ مهمِ کوتاه:

// بزرگ‌ترین تصمیم — عکسِ فوری در برابرِ ارجاع: دو راه بود. یا CartItem = { productId, quantity }ِ لخت (سبک، ولی برای رندرِ سبد باید محصولات را دوباره fetch کنی)، یا عکسِ فوریِ نمایشی را کنارِ آن نگه داری. دومی را انتخاب کردم چون سبد باید آنی و آفلاین-پسند رندر شود (به‌ویژه سبدِ مهمان در localStorage). هزینه‌اش تکرارِ کنترل‌شدهٔ داده است، که با «سرور در checkout بازاعتبارسنجی می‌کند» مهار شده.

// unitPrice قفل‌شده در لحظهٔ افزودن (تصمیمِ مهم): اگر قیمتِ زندهٔ محصول را می‌خواندم، مبلغِ سبدِ کاربر ممکن بود وسطِ خرید تغییر کند — تجربهٔ بد و بحثِ حقوقی. قیمت را در لحظهٔ افزودن ثبت می‌کنم؛ اختلافِ احتمالی با قیمتِ روز، مسئلهٔ checkout است نه نمایشِ سبد.

// جمع‌ها مشتق‌اند، نه ذخیره‌شده: عمداً subtotal/total را در Cart نگذاشتم. اگر ذخیره‌شان کنم، هر تغییرِ quantity باید دو جا آپدیت شود و دیر یا زود ناهماهنگ می‌شوند. تنها منبعِ حقیقت items است؛ CartTotals خروجیِ یک تابعِ خالص (computeTotals(cart)) خواهد بود که جایش utils/cart.ts است، نه این فایل.

// currency روی خودِ Cart: یک نگهبانِ ساده تا اقلامِ چندارزی قاطی نشوند؛ افزودنِ کالایی با ارزِ متفاوت باید در store رد شود.

// updatedAt از الان هست چون به تصمیمِ merge بند است: یادت هست یکی از سه تصمیمِ بنیادی «ادغامِ سبدِ مهمان پس از ورود» بود؟ این فیلد همان‌جا لازم می‌شود (کدام سبد تازه‌تر است). گذاشتمش تا وقتی به آن تصمیم رسیدیم، تایپ آماده باشد — بدونِ اینکه الان مجبور به تصمیم باشم.

// چه چیزی این‌جا نیست (عمدی): تابعِ computeTotals، منطقِ merge، و CartItemِ سمتِ سرور (که فقط { productId, quantity } است و در services/cart تعریف می‌شود). این فایل فقط شکلِ حالتِ کلاینت را می‌گوید.



// رسیدیم به types/cart.ts — و این دقیقاً همان قدمِ درستی است که پیامِ قبل پیشنهادش کردم: دومین تکهٔ لایهٔ تایپ، که مستقیماً روی Product و Moneyِ فایلِ قبل سوار می‌شود. و مهم‌تر، این تایپ همان قراردادی است که stores/cart رویش ساخته می‌شود — یعنی داریم زمین را برای اولین storeِ واقعی صاف می‌کنیم.

// فرض‌های مهم (چون این تایپ روی محاسباتِ پول می‌نشیند و اشتباهش گران است):

// CartItem یک عکسِ فوری از محصول را نگه می‌دارد، نه فقط productId: سبد باید بتواند بدونِ یک fetchِ دیگر رندر شود (عنوان، تصویر، قیمت)؛ ولی چون قیمت ممکن است بینِ افزودن و پرداخت تغییر کند، unitPrice را در لحظهٔ افزودن ثبت می‌کنم و منبعِ حقیقتِ نمایشِ سبد همین است — سرور موقعِ checkout دوباره اعتبارسنجی می‌کند.
// quantity صحیح و مثبت: حداقل ۱؛ صفر یعنی حذف، نه آیتمِ صفر.
// مبالغِ جمع، مشتق هستند نه ذخیره‌شده: Cart خودش subtotal/total را به‌عنوان فیلد نگه نمی‌دارد بلکه با یک تابعِ خالص محاسبه می‌شوند — تا هیچ‌وقت جمع با آیتم‌ها ناهماهنگ نشود. تایپ فقط شکلِ خروجیِ آن محاسبه (CartTotals) را تعریف می‌کند.
// همه‌چیز Money، هیچ numberِ لختِ پول: ادامهٔ همان تصمیمِ integer/واحدِ صریحِ فایلِ قبل.


// خبرِ خوب همان است که ادامه دارد: دو تا از چهار فایلِ تایپ بسته شد. product.ts و cart.ts حالا با هم یک زیرمجموعهٔ منسجم‌اند و stores/cart دیگر یک زمینِ محکم برای نشستن دارد. این دومین قدمِ درستِ پشتِ‌سرِ هم است.

// دو فایلِ تایپِ خواهر باقی مانده، هر دو کوچک و بی‌بدهی:

// types/user.ts — User, Address; زیربنای کلِ قطاعِ auth (Login/Register/Account).
// types/order.ts — Order, OrderItem, OrderStatus; که CartItem را به یک سفارشِ نهایی‌شده تبدیل می‌کند و OrderHistory/OrderDetails منتظرش‌اند.
// پیشنهادم: types/order.ts را بعدی برویم، چون مستقیماً روی همین CartItem سوار است (سفارش، عکسِ فوریِ سبد در لحظهٔ خرید است) و حلقهٔ فکری‌مان را با سبد کامل می‌کند. ولی اگر ترجیح می‌دهی اول user.ts تا قطاعِ auth راه بیفتد، همان را می‌روم. کدام؟