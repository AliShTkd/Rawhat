
// src/types/product.ts
import type { BrandRef } from "./brand";
import type { RatingSummary } from "./review";
import type { Paginated } from "./api";

/**
 * بازصادرِ `Paginated` — خانهٔ اصلی‌اش حالا `api.ts` است (زیرساخت، نه محصول).
 * این خط فقط برای عقب‌سازگاری است: هر جای اپ که هنوز
 * `import { Paginated } from "./product"` دارد بی‌شکست کار می‌کند.
 * مصرف‌کنندگانِ جدید بهتر است مستقیم از `./api` بیاورند.
 */
export type { Paginated };

/**
 * پول — مبلغِ صحیح برای پرهیز از خطای اعشاریِ ممیزِ شناور.
 * `amount` بر حسبِ کوچک‌ترین واحد (ریال/سِنت)، نه اعشاری.
 */
export interface Money {
  /** مبلغِ صحیح بر حسبِ کوچک‌ترین واحدِ پول. */
  amount: number;
  /** کدِ ارز، مثلِ "IRR". */
  currency: string;
}

/** تصویرِ محصول با متنِ جایگزین برای دسترس‌پذیری. */
export interface ProductImage {
  url: string;
  alt: string;
  width?: number;
  height?: number;
}

/** ارجاعِ سبکِ دسته — همانی که کارت و breadcrumb مصرف می‌کنند. */
export interface CategoryRef {
  id: string;
  name: string;
  slug: string;
}

/** وضعیتِ موجودی — صریح‌تر از یک بولینِ ساده. */
export type ProductAvailability = "in_stock" | "low_stock" | "out_of_stock" | "preorder";

/**
 * محصولِ سبک — برای لیست‌ها، کارت‌ها و شبکه‌ها.
 * فقط چیزی که برای رندرِ یک کارت لازم است.
 */
export interface Product {
  id: string;
  slug: string;
  title: string;

  /** تصویرِ اصلی برای کارت. */
  image: ProductImage;

  price: Money;
  /** قیمتِ پیش از تخفیف، اگر تخفیفی هست. */
  compareAtPrice?: Money;

  availability: ProductAvailability;
  category: CategoryRef;

  /**
   * برندِ محصول — الحاقِ رسمی‌شده (از `brand.ts`).
   * اختیاری، چون هر محصول لزوماً برند ندارد.
   * کارتِ محصول و چیپِ فیلتر این را نشان می‌دهند.
   */
  brand?: BrandRef;

  /**
   * خلاصهٔ امتیاز — الحاقِ رسمی‌شده (از `review.ts`).
   * فقط میانگین و تعداد، نه خودِ نظرها؛ برای ستاره‌های روی کارت.
   * اختیاری، چون محصولِ بی‌نظر خلاصه‌ای ندارد.
   */
  rating?: RatingSummary;
}

/**
 * محصولِ سنگین — برای صفحهٔ جزئیات.
 * `Product` را با دادهٔ غنی‌تری که فقط صفحهٔ جزئیات می‌خواهد گسترش می‌دهد.
 */
export interface ProductDetail extends Product {
  /** گالریِ کاملِ تصاویر. */
  images: ReadonlyArray<ProductImage>;
  description: string;
  /** مشخصاتِ فنی به‌شکلِ کلید/مقدار. */
  specifications: ReadonlyArray<{ label: string; value: string }>;
  /** موجودیِ عددی، اگر سرور فاش کند — برای «فقط ۳ عدد مانده». */
  stock?: number;
  sku?: string;
}

/** یک صفحهٔ نتیجهٔ محصول — همان الگوی `Paginated`ِ حالا در `api.ts`. */
export type ProductPage = Paginated<Product>;













