
// src/types/api.ts

/**
 * پاکتِ موفقیتِ استاندارد — هر پاسخِ موفقِ سرور این شکل را دارد.
 * `data` بارِ اصلی است؛ `meta` اطلاعاتِ جانبیِ اختیاری.
 */
export interface ApiSuccess<T> {
  data: T;
  meta?: ApiMeta;
}

/** متادیتای جانبیِ پاسخ — مثلِ زمانِ سرور یا نسخهٔ API. */
export interface ApiMeta {
  requestId?: string;
  timestamp?: string;
}

/**
 * دستهٔ خطا — تا UI رفتارِ درست را انتخاب کند.
 * هر کدام یک واکنشِ متفاوت: شبکه→تلاشِ دوباره، auth→هدایت به ورود،
 * validation→نمایشِ خطا زیرِ فیلد، notFound→صفحهٔ ۴۰۴.
 */
export type ApiErrorKind =
  | "network"        // اصلاً به سرور نرسید
  | "timeout"
  | "auth"           // ۴۰۱/۴۰۳ — ورود یا دسترسی لازم
  | "validation"     // ۴۲۲ — خطای فرم، فیلد‌به‌فیلد
  | "not_found"      // ۴۰۴
  | "rate_limit"     // ۴۲۹
  | "server"         // ۵xx
  | "unknown";

/**
 * خطای ساخت‌یافتهٔ API — شکلِ واحدی که هر سرویس پرتاب/برمی‌گرداند.
 * رشته نیست تا UI بتواند روی `kind` تصمیم بگیرد.
 */
export interface ApiError {
  kind: ApiErrorKind;
  /** پیامِ خواندنیِ فارسی برای نمایشِ مستقیم. */
  message: string;
  /** کدِ HTTP، اگر پاسخی رسیده باشد. */
  status?: number;
  /** کدِ داخلیِ سرور برای تشخیصِ دقیق‌تر، مثلِ `EMAIL_TAKEN`. */
  code?: string;
  /**
   * خطاهای فیلد‌به‌فیلد برای `validation` —
   * کلید نامِ فیلد، مقدار پیامِ آن فیلد. فرم‌ها این را زیرِ ورودی نشان می‌دهند.
   */
  fieldErrors?: Record<string, string>;
}

/** پاسخِ سرور = یا موفقیت یا خطا. سرویس این را به `ApiSuccess` یا throw تبدیل می‌کند. */
export type ApiResult<T> = ApiSuccess<T> | { error: ApiError };

/**
 * پارامترهای صفحه‌بندیِ درخواست — سمتِ *ورودیِ* صفحه‌بندی.
 * قرینهٔ `Paginated<T>` که سمتِ *خروجی* است.
 */
export interface PageParams {
  page?: number;
  /** تعدادِ آیتم در هر صفحه. */
  pageSize?: number;
}

/**
 * پاسخِ صفحه‌بندی‌شدهٔ عمومی — سمتِ *خروجی*.
 * از `product.ts` به این‌جا منتقل می‌شود، چون زیرساخت است نه دامنهٔ محصول.
 */
export interface Paginated<T> {
  items: ReadonlyArray<T>;
  page: number;
  pageSize: number;
  /** تعدادِ کلِ آیتم‌ها در همهٔ صفحه‌ها. */
  total: number;
  /** آیا صفحهٔ بعدی وجود دارد — برای دکمهٔ «بیشتر». */
  hasMore: boolean;
}

/**
 * ماشینِ حالتِ یک درخواستِ ناهمگام — چیزی که هر store/صفحه نگه می‌دارد.
 * صریح، تا UI بینِ «هنوز شروع نشده» و «در حالِ بارگذاری» فرق بگذارد.
 */
export type RequestStatus = "idle" | "loading" | "success" | "error";

/**
 * ظرفِ داده + وضعیت — الگوی پرتکرارِ استورها.
 * `status` تصمیمِ رندر را می‌گیرد؛ `data` و `error` بارِ متناظرند.
 */
export interface AsyncState<T> {
  status: RequestStatus;
  data?: T;
  error?: ApiError;
}

/** حالتِ اولیهٔ استاندارد برای هر `AsyncState` — تا استورها تکرارش نکنند. */
export const initialAsyncState: AsyncState<never> = { status: "idle" };




















// نکاتِ مهمِ کوتاه:

// مهم‌ترین اعتراف — Paginated باید از product.ts به این‌جا کوچ کند: یادت هست همان اولِ کار Paginated<T> را داخلِ product.ts تعریف کردم، چون آن موقع اولین جایی بود که لازمش داشتم؟ حالا که brand, review و آینده‌اش هم مصرفش می‌کنند، روشن شد که این یک تایپِ زیرساختی است، نه محصول‌محور. جایِ درستش این‌جاست. این دقیقاً مثلِ Address است که آگاهانه در پایین‌ترین لایه گذاشتم — ولی این‌بار اولش را اشتباه حدس زدم و حالا اصلاحش می‌کنم. این دومین بدهیِ product.ts است که باید در آن بازنگری بسته شود.

// ApiError ساخت‌یافته، نه رشته — تصمیمِ بنیادیِ این فایل: اگر خطا فقط string بود، هر کامپوننت مجبور می‌شد متنِ خطا را پارس کند تا بفهمد «این ۴۰۱ است یا ۴۲۲؟». با kind، تصمیمِ UI یک switch ساده می‌شود: auth→ هدایت به ورود، validation→ پخشِ fieldErrors زیرِ ورودی‌ها، network→ دکمهٔ تلاشِ دوباره. این همان چیزی است که پنج صفحهٔ auth و فرمِ نظر مستقیماً بهش تکیه می‌کنند.

// fieldErrors پلِ مستقیم به فرم‌هاست: یادت هست LoginCredentials, RegisterInput, CreateReviewInput را ساختیم؟ وقتی سرور می‌گوید «این ایمیل قبلاً ثبت شده»، این خطا باید زیرِ فیلدِ ایمیل بنشیند، نه بالای فرم. fieldErrors: Record<string, string> همان مسیر است — کلیدش دقیقاً نامِ فیلدِ همان تایپ‌های ورودی است.

// AsyncState<T> + initialAsyncState — الگوی مشترکِ همهٔ استورها: این اولین باری است که در کلِ این مسیر یک مقدارِ اجراشونده نوشتم، نه صرفاً تایپ (initialAsyncState یک const واقعی است). عمدی است: هر استوری که می‌سازیم (cart, auth, …) همین ظرفِ {status, data, error} را تکرار می‌کند، پس یک حالتِ اولیهٔ مشترک تکرار را حذف می‌کند. never در AsyncState<never> ترفندِ کوچکی است تا این ثابت با هر AsyncState<T> سازگار باشد.

// PageParams قرینهٔ Paginated: یکی ورودیِ درخواست (چه صفحه‌ای می‌خواهی)، دیگری خروجیِ پاسخ (چه گرفتی). کنارِ هم گذاشتنشان در همین فایل، تقارنِ «request/response»ِ صفحه‌بندی را یک‌جا نگه می‌دارد.

// چه چیزی این‌جا نیست (عمدی): خودِ fetch/axios wrapper (کارِ services/http.ts یا lib/api-client)، منطقِ retry/refresh-token (زیرساختِ سرویس)، و URLها/endpointها. این فایل فقط شکلِ گفت‌وگو را می‌گوید، نه مکانیزمش را.





// رسیدیم به types/api.ts — و این فایل جنسش با آن هفت‌تای قبلی فرق دارد. تا الان هر فایل یک دامنه بود (محصول، سبد، سفارش…)؛ این یکی یک زیرساخت است — لایه‌ای که زیرِ همهٔ دامنه‌ها می‌نشیند و شکلِ گفت‌وگوی کلاینت با سرور را تعریف می‌کند. هر تابعِ services/* که هنوز ننوشته‌ایم، از این فایل تغذیه می‌کند. و همین، یک بدهیِ پنهان از product.ts را هم رو می‌کند که باید صادقانه بگویم.

// فرض‌های مهم:

// پاکتِ یکدستِ پاسخ: هر پاسخِ سرور یک شکلِ قابل‌پیش‌بینی دارد تا هر سرویس مجبور نباشد جداگانه حدس بزند «داده کجاست، خطا کجاست».
// خطا یک تایپِ ساخت‌یافته است، نه رشته: چون UI باید بینِ «خطای شبکه»، «۴۰۱ ورود لازم»، و «۴۲۲ خطای اعتبارسنجیِ فرم» فرق بگذارد — هر کدام رفتارِ متفاوت.
// حالتِ درخواست به‌شکلِ ماشینِ حالتِ صریح: idle | loading | success | error — همان چیزی که هر store و هر صفحه برای نشان‌دادنِ اسپینر/خطا لازم دارد.
// Paginated بالاخره خانهٔ درستش را پیدا می‌کند: این‌جا، نه در product.ts.



// خب، این فایل تصویر را عوض کرد. تا الان هفت فایلِ دامنه داشتیم؛ حالا اولین فایلِ زیرساخت هم اضافه شد و یک چیزِ مهم را روشن کرد: لایهٔ تایپ دارد به دو طبقه تقسیم می‌شود —

// طبقه	فایل‌ها	نقش
// زیرساخت	api.ts	پاکت، خطا، صفحه‌بندی، حالتِ ناهمگام
// دامنه	product, cart, user, order, category, brand, review	شکلِ دادهٔ کسب‌وکار
// ولی مهم‌تر از آن، این فایل بدهیِ product.ts را از دو مورد به یک فهرستِ جدی رساند. حالا سه چیز آن‌جا معلق است:

// الحاق/کوچِ معلق	از کجا	نوع
// brand?: BrandRef	brand.ts	افزودنِ فیلد
// rating?: RatingSummary	review.ts	افزودنِ فیلد
// کوچِ Paginated به api.ts	همین فایل	جابه‌جایی
// و این سومی از دو تای قبلی جدی‌تر است، چون یک جابه‌جایی است نه افزودن — یعنی importهای موجود در brand.ts و review.ts که Paginated را از product.ts می‌کشند، باید به api.ts تغییر مسیر دهند. هرچه بیشتر صبر کنیم، importهای بیشتری به مسیرِ اشتباه بند می‌شوند.

// پس حالا با اطمینانِ بیشتری همان حرفِ پیامِ قبل را می‌زنم، این‌بار جدی‌تر: فکر می‌کنم واقعاً وقتِ آن بازنگریِ product.ts است، پیش از هر فایلِ جدید. سه بدهی جمع شده و یکی‌شان دارد به فایل‌های دیگر سرایت می‌کند.

// پیشنهادم:

// بازنگریِ product.ts (حالا قویاً پیشنهادِ اول) — دو فیلد را رسمی کن، Paginated را به api.ts منتقل و از product.ts بازصادر کن (تا importهای قدیمی نشکنند)، و بدهی را ببند.
// utils/money.ts — پرمصرف‌ترین تکهٔ اجراشونده.
// stores/cart — که حالا می‌تواند از AsyncStateِ همین فایل استفاده کند.
// ولی اگر باز هم ترجیحت فایلِ تایپِ بعدی است، می‌روم سراغش. کدام؟