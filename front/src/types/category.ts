

// src/types/category.ts
import type { CategoryRef, ProductImage } from "./product";

// یک منبعِ حقیقت: همان ارجاعِ سبک که کارتِ محصول استفاده می‌کند.
export type { CategoryRef };

/**
 * یک دستهٔ کامل به شکلِ تختِ خودارجاع — نزدیک به دادهٔ سرور.
 * ساختِ درخت با کنارِ‌هم‌گذاریِ `parentId`ها انجام می‌شود.
 */
export interface Category {
  id: string;
  slug: string;
  name: string;

  /** والد؛ `null` یعنی دستهٔ ریشه (سطحِ اول). */
  parentId: string | null;

  /** آیکونِ اختیاری برای منو. */
  iconUrl?: string;
  /** تصویرِ بنرِ اختیاری برای بالای صفحهٔ دسته. */
  image?: ProductImage;

  /** تعدادِ محصولاتِ این دسته — برای نمایشِ «(۱۲۴)» کنارِ نام. */
  productCount?: number;
  /** ترتیبِ نمایش در منو؛ کوچک‌تر بالاتر. */
  sortOrder?: number;
}

/**
 * گرهِ درختِ دسته — شکلِ تودرتو برای رندرِ منوی چندسطحی.
 * از `Category` می‌آید ولی `children` را به‌جای `parentId` تودرتو دارد.
 */
export interface CategoryTreeNode extends Category {
  children: ReadonlyArray<CategoryTreeNode>;
}

/**
 * شکلِ کاملِ صفحهٔ دسته — متادیتای سئو و مسیرِ راهنما.
 * `Category.tsx` این را برای هدرِ صفحه و breadcrumb مصرف می‌کند.
 */
export interface CategoryDetail extends Category {
  /** توضیحِ بالای صفحهٔ دسته. */
  description?: string;
  /** عنوانِ سئو؛ اگر نبود از `name` استفاده کن. */
  seoTitle?: string;
  seoDescription?: string;

  /**
   * مسیرِ راهنما از ریشه تا این دسته (شاملِ خودش)، به‌ترتیب.
   * برای کامپوننتِ breadcrumb که قبلاً درباره‌اش حرف زدیم.
   */
  breadcrumb: ReadonlyArray<CategoryRef>;
}













// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — تخت در برابرِ تودرتو، هر دو: یک تلهٔ کلاسیک این بود که فقط یکی را انتخاب کنم. اگر فقط parentIdِ تخت می‌داشتم، منوی چندسطحی باید هر بار درخت را در UI بازسازی می‌کرد؛ اگر فقط childrenِ تودرتو، به‌روزرسانی و پیدا‌کردنِ یک دسته سخت می‌شد. هر دو را دارم چون دو مصرفِ متفاوت‌اند: سرور/کش تختِ خودارجاع را می‌دهد (Category)، و یک تابعِ خالصِ buildTree() (جایش utils) آن را به CategoryTreeNode تبدیل می‌کند برای منو.

// CategoryRef بازصادر شد، نه بازتعریف: با export type { CategoryRef } همان تایپِ product.ts را از این‌جا هم در دسترس گذاشتم. پس هر کس که با دسته کار می‌کند فقط از types/category import می‌کند و لازم نیست بداند CategoryRef فیزیکی کجا زندگی می‌کند — ولی همچنان یک تعریف در کلِ اپ هست. این دقیقاً همان انضباطِ «یک منبعِ حقیقت» است.

// parentId: string | null صریح: null را عمداً به‌جای undefined گذاشتم چون «ریشه‌بودن» یک حالتِ معنادارِ داده است (این دسته والد ندارد)، نه «نمی‌دانیم». تمایزی که موقعِ ساختِ درخت مهم می‌شود.

// breadcrumb این‌جا آماده شد: یادت هست در صفحه‌های محصول/دسته چند بار breadcrumb را نام بردیم؟ حالا شکلش هست — آرایه‌ای از CategoryRefِ سبک، از ریشه تا خودِ دسته. کامپوننتِ breadcrumb دیگر لازم نیست خودش سلسله‌مراتب را حدس بزند.

// چه چیزی این‌جا نیست (عمدی): تابعِ buildTree/findCategoryBySlug (کارِ utils/category.ts)، fetchCategories/fetchCategory (کارِ services/categories)، و فیلترها/مرتب‌سازیِ صفحهٔ دسته (که به types/search یا پارامترهای سرویس تعلق دارند، چون بینِ Search و Category مشترک‌اند). فقط شکلِ خودِ دسته.



// رسیدیم به types/category.ts — و این یک تکمله‌ی هوشمندانه است. فکر می‌کردم لایهٔ تایپ با آن چهار فایل بسته شد، ولی حق با توست که این جدا بیاید: در product.ts فقط یک CategoryRefِ سبک تعریف کردم (همان چیزی که کارتِ محصول لازم داشت)، ولی خودِ صفحهٔ Category و منوی دسته‌بندی به چیزِ بیشتری نیاز دارند — درختِ دسته‌ها، والد/فرزند، و متادیتای صفحه. این فایل همان شکافِ به‌جامانده را پر می‌کند.

// فرض‌های مهم (چون دسته‌بندی ذاتاً درختی است و مدلِ اشتباهش کلِ ناوبری را خراب می‌کند):

// CategoryRef را از product.ts دوباره تعریف نمی‌کنم: آن‌جا هست، این‌جا import و بازصادرش می‌کنم تا یک منبعِ حقیقت بماند. تکرارِ تایپ همان بدهی‌ای است که کلِ این مسیر ازش پرهیز کردیم.
// درخت به دو شکل: یک Category تختِ خودارجاع (با parentId) که به داده‌ی سرور نزدیک است، و یک CategoryTreeNode که فرزندان را تودرتو دارد برای رندرِ منو. UI به دومی نیاز دارد، API معمولاً اولی را می‌دهد.
// slug ستونِ فقرات است: چون Category.tsx با slug از URL کار می‌کند، نه id.
// الگوی «سبک/سنگین» را ادامه می‌دهم: Category (ردیف/منو) در برابرِ CategoryDetail (صفحهٔ کامل با متادیتای سئو و بنر).



// خب، حالا لایهٔ تایپ واقعاً پنج‌ضلعی شد و منسجم‌تر از قبل:

// فایل	هسته	نکتهٔ کلیدی
// product.ts	Product, Money, CategoryRef	مبنای همه
// cart.ts	CartItem, Cart	عکسِ فوریِ نیمه‌زنده
// user.ts	User, Address, AuthSession	بی‌توکن، امن
// order.ts	Order, OrderStatus	عکسِ فوریِ منجمد
// category.ts	Category, CategoryTreeNode	تخت + تودرتو
// و یک الگوی زیبا در کلِ این پنج فایل تکرار شد که ارزشِ یک لحظه مکث دارد: «سبک برای لیست، سنگین برای جزئیات» — Product/ProductDetail, Order/OrderSummary, Category/CategoryDetail. سه دامنه، یک انضباطِ واحد. این همان انسجامی است که وقتی از پایین به بالا می‌سازی به‌دست می‌آید و وقتی صفحه‌ روی هوا می‌چینی هرگز.

// مسیرهای بعدی همان‌اند که گفتم، و حالا category.ts یکی‌شان را کمی وسوسه‌انگیزتر کرد:

// utils/money.ts (formatMoney) — ریزترین، بیشترین مصرف‌کننده. هنوز پیشنهادِ اولم.
// utils/category.ts (buildTree, findBySlug) — حالا که تایپش هست، این تابع‌ها منوی دسته و breadcrumb را زنده می‌کنند.
// stores/cart — کم‌ریسک، بی‌نیاز به تصمیم.
// services/auth + stores/auth — پنج صفحه، ولی نیازمندِ «کوکی یا توکن».
// اگر بخواهم صادق باشم، الان که دو فایلِ تایپ (money در product, و درختِ category) هر دو یک تابعِ utils را طلب می‌کنند، شاید بهترین قدم یک utils/ دوتایی باشد: اول formatMoney، بعد buildTree. ولی تصمیم با توست — کدام فایل بعدی