
// src/services/orderService.ts
import { http } from "./http";
import { useOrderStore } from "../stores/orderStore";
import { useCartStore } from "../stores/cartStore";
import type { OrderQuery } from "../stores/orderStore";
import type { Order, OrderSummary, CheckoutPayload } from "../types/order";
import type { Paginated } from "../types/api";

/**
 * سرویسِ سفارش = رهبرِ عملیاتِ برگشت‌ناپذیر.
 * ضدِ cartService: هیچ خوش‌بینی‌ای در checkout نیست، چون پول برگشت‌پذیر نیست.
 * دو جنسِ متفاوت زیرِ یک سقف:
 *   - خواندن‌ها (loadOrders/loadOrderDetail) → قالبِ productService، کش‌آگاه.
 *   - checkout → صبورترین گذارِ کلِ برنامه، دو-استوره، ایدمپوتنت.
 */

function toParams(query: OrderQuery): URLSearchParams {
  const p = new URLSearchParams();
  if (query.status) p.set("status", query.status);
  if (query.page && query.page > 1) p.set("page", String(query.page));
  return p;
}

/**
 * فهرستِ سفارش‌ها — یک خواندنِ کش‌آگاه، دقیقاً مثلِ loadProducts.
 * سفارش‌های گذشته تغییر نمی‌کنند، پس کش این‌جا حتی امن‌تر از محصول است.
 */
export async function loadOrders(
  query: OrderQuery,
  opts: { force?: boolean } = {},
): Promise<void> {
  const store = useOrderStore.getState();
  if (!opts.force && store.getPageOrders(query) !== undefined) return;

  store.setListLoading(query);
  const res = await http.get<Paginated<OrderSummary>>(
    `/orders?${toParams(query).toString()}`,
  );

  if (res.ok) store.setPage(query, res.data);
  else store.setError(res.error);
}

/**
 * جزئیاتِ یک سفارش — کشِ سنگین و ماندگار.
 * سفارشِ ثبت‌شده تقریباً تغییرناپذیر است؛ اگر یک‌بار آمد، دوباره نمی‌آید.
 */
export async function loadOrderDetail(
  orderId: string,
  opts: { force?: boolean } = {},
): Promise<void> {
  const store = useOrderStore.getState();
  if (!opts.force && store.detailById[orderId]) return;

  store.setDetailLoading(orderId);
  const res = await http.get<Order>(`/orders/${orderId}`);

  if (res.ok) store.setDetail(res.data);
  else store.setError(res.error);
}

/**
 * ثبتِ سفارش (checkout) — برگشت‌ناپذیرترین گذارِ برنامه.
 * نه خوش‌بینی، نه حدس؛ صبر تا تأییدِ قطعیِ سرور، بعد دو گذارِ هم‌زمان.
 * @returns شناسهٔ سفارشِ ثبت‌شده در موفقیت، وگرنه null (برای ناوبریِ کامپوننت).
 */
export async function checkout(
  payload: CheckoutPayload,
): Promise<string | null> {
  const orders = useOrderStore.getState();
  const cart = useCartStore.getState();

  // قفلِ صریح: تا سرور جواب ندهد، هیچ سفارشی وجود ندارد.
  orders.setPlacing();

  // کلیدِ ایدمپوتنسی: سپرِ «دوبار خرید». کلیکِ دوم = همان سفارش، نه سفارشِ نو.
  const idempotencyKey = crypto.randomUUID();

  const res = await http.post<Order>(
    "/orders",
    payload,
    { headers: { "Idempotency-Key": idempotencyKey } },
  );

  if (res.ok) {
    // دو گذارِ هم‌زمان — تنها جایی که یک موفقیت به دو استور دست می‌زند.
    orders.prependNewOrder(res.data); // سفارشِ نو به بالای فهرست.
    cart.clearCart();                 // سبد تبدیل به سفارش شد؛ خالی می‌شود.
    return res.data.id;
  }

  // شکست → سفارشی ساخته نشده؛ فقط خطا. سبد دست‌نخورده می‌ماند تا کاربر دوباره تلاش کند.
  orders.setPlaceError(res.error);
  return null;
}





















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — checkout قرینهٔ کاملِ cartService است، و همین آموزنده است: دو سرویسِ همسایه، دو فلسفهٔ متضاد. سبد خوش‌بین بود چون ارزان و برگشت‌پذیر بود؛ سفارش بدبین است چون گران و برگشت‌ناپذیر است. اگر همان قالبِ خوش‌بینانهٔ سبد را کورکورانه این‌جا کپی می‌کردم، فاجعه‌بارترین باگِ ممکن ساخته می‌شد: تأییدِ خریدی که هنوز قطعی نشده. باز همان درسِ همیشگی، این‌بار با بالاترین ریسک: امضا و رفتار از ماهیتِ عملیات می‌آید (برگشت‌پذیر؟ گران؟) نه از فایلِ همسایه.

// دو-استوره بودنِ موفقیت — تنها سرویسی که یک if (res.ok) دو استور را می‌راند: prependNewOrder و clearCart باید با هم رخ دهند، وگرنه ناهماهنگی. این‌جا سرویس نقشِ واقعیِ «رهبرِ ارکستر» را به کامل‌ترین شکلش بازی می‌کند: نه فقط یک استور، که هماهنگیِ بینِ دو استور را در یک نقطهٔ اتمی می‌نشاند. اگر این را به کامپوننت می‌سپردم، یکی clearCart را فراموش می‌کرد و سبدِ شبح باقی می‌ماند.

// crypto.randomUUID() — سرویس این‌بار خودش شناسه می‌سازد، برخلافِ همیشه: در سه سرویسِ قبلی، هر شناسه از سرور می‌آمد. این‌جا برعکس: کلید را قبل از تماس می‌سازم و می‌فرستم، چون کارکردش دقیقاً محافظت در برابرِ تکرارِ همان تماس است. اگر شناسه از سرور می‌آمد، دیگر برای جلوگیری از دوبار-ارسال فایده نداشت — باید پیش از خطر وجود داشته باشد، نه بعدش.

// checkout شناسهٔ سفارش برمی‌گرداند (string | null)، نه boolean: تکاملِ همان منطقِ login. آن‌جا boolean کافی بود («موفق شدی؟»)، ولی این‌جا کامپوننت بعد از موفقیت باید به صفحهٔ همان سفارشِ مشخص ناوبری کند (/orders/{id}) — پس فقط «بله» کافی نیست، خودِ id لازم است. باز همان اصل: خروجیِ سرویس دقیقاً به‌اندازهٔ تصمیمی که کامپوننت باید بگیرد اطلاعات می‌دهد، نه بیشتر نه کمتر.

// در شکستِ checkout، سبد دست‌نخورده می‌ماند — عمدی: دقتِ ظریف در ترتیب: clearCart فقط داخلِ شاخهٔ res.ok است. اگر پرداخت شکست خورد، سبد باید سالم بماند تا کاربر بتواند دوباره تلاش کند. اگر سبد را قبل از تأیید خالی می‌کردم (خوش‌بینانه)، یک checkout ِ شکست‌خورده کاربر را با سبدِ خالی و بدونِ سفارش رها می‌کرد — بدترین ترکیب. برگشت‌ناپذیری یعنی هیچ‌چیز قبل از تأیید تغییر نمی‌کند.

// چه چیزی این‌جا نیست: درگاهِ پرداخت و ری‌دایرکتِ ۳DS (یک جریانِ مجزا که شاید کلِ checkout را async-تر کند)، لغو/مرجوعیِ سفارش (گذارهای مستقلِ خودشان با قوانینِ سرور)، پیگیریِ وضعیتِ ارسال (احتمالاً polling یا websocket، نه این‌جا)، و اعتبارسنجیِ فرمِ آدرس/پرداخت (کارِ کامپوننت). این فایل فقط رهبریِ خواندنِ سفارش‌ها و آن یک گذارِ برگشت‌ناپذیرِ checkout است.



// سرویسِ چهارم — و این‌جا باید سخت‌ترین وسوسهٔ کلِ لایه را بکشم، چون تازه از cartService آمده‌ایم و ذهن هنوز گرمِ خوش‌بینی است: «سبد و سفارش که همسایه‌اند؛ checkout هم لابد خوش‌بینانه است — دکمه را بزن، سفارش را فوری نشان بده.» نه. و این "نه" شدیدترین "نه"ی کلِ این چهار فایل است. سبد خوش‌بینانه بود چون برگشت‌پذیر بود — اگر افزودن شکست می‌خورد، restore(snapshot) و انگار هیچ نشد. ولی checkout برگشت‌ناپذیر است: پولی جابه‌جا می‌شود، موجودی‌ای رزرو می‌شود، ایمیلی می‌رود. نمی‌شود یک سفارشِ خوش‌بینانه نشان داد و بعد restore کرد — آن‌وقت به کاربر گفته‌ای «خریدت انجام شد» و بعد پسش گرفته‌ای. پس checkout ضدِ خوش‌بینانه‌ترین عملیاتِ کلِ برنامه است: صبورترین، محتاط‌ترین، و تنها جایی که دوبار اجرا شدن خودش یک فاجعه است.

// قبل از کد، سه تصمیمِ بزرگ که این سرویس را از هر سه قبلی جدا می‌کنند:

// تصمیمِ بزرگِ اول — checkout پدرِ همهٔ عملیاتِ صبور است: هیچ خوش‌بینی، هیچ حدس. در cartService ترتیب وارونه بود (UI اول). این‌جا ترتیب به محتاط‌ترین حالتِ ممکن برمی‌گردد — حتی محتاط‌تر از authService: استور را در حالتِ placing قفل کن، منتظرِ سرور بمان، و فقط و فقط بعد از تأییدِ قطعیِ سرور سفارش را واقعی کن. هیچ سفارشی قبل از پاسخِ سرور وجود ندارد. چون تنها چیزی که از «UIِ همیشه‌loading» بدتر است، «سفارشی که کاربر فکر می‌کند ثبت شده ولی نشده» است.

// تصمیمِ بزرگِ دوم — checkout یک رهبرِ دو-استوره است: در موفقیت هم orderStore و هم cartStore را می‌راند. این اولین سرویسی است که موفقیتش به دو استور دست می‌زند. وقتی سرور سفارش را تأیید کرد، دو گذارِ اتمی باید با هم رخ دهند: سفارشِ نو به بالای فهرست بنشیند (orderStore.prependNewOrder — همان که در استور کاشتیم) و سبد خالی شود (cartStore.clearCart). چون سبد بعد از خرید دیگر معنا ندارد — تبدیل به سفارش شده. اگر فقط یکی را می‌زدم، کاربر سفارش را می‌دید ولی سبدِ پرِ قبلی هم سرِ جایش بود — یک ناهماهنگیِ گیج‌کننده.

// تصمیمِ بزرگِ سوم — کلیدِ ایدمپوتنسی: چون تنها خطای واقعاً ترسناک، دوبار خرید است. شبکه لغزنده است؛ کاربر روی «پرداخت» می‌زند، اسپینر می‌بیند، بی‌صبر می‌شود، دوباره می‌زند. بدونِ محافظت، دو سفارش و دو پرداخت. پس قبل از ارسال یک idempotencyKey می‌سازم و می‌فرستم؛ سرور با دیدنِ کلیدِ تکراری، همان سفارشِ قبلی را برمی‌گرداند نه یک سفارشِ نو. این تنها سرویسی است که خودش یک شناسه تولید می‌کند پیش از آنکه سرور چیزی بدهد.








// خب، چهار سرویس شد و حالا کلِ طیفِ رفتاری روشن است — و این ردیفِ چهارم، دو سرِ طیف را کنارِ هم می‌گذارد:

// productService	authService	cartService	orderService (checkout)
// جنسِ عملیات	خواندن	گذارِ هویت	کنشِ خوش‌بینانه	کنشِ برگشت‌ناپذیر
// خوش‌بینی	—	ندارد	کامل	صفرِ مطلق
// ترتیب	شبکه → استور	loading → شبکه	استور → شبکه → آشتی	قفل → شبکه → دو گذار
// چند استور؟	یک	یک	یک	دو (order + cart)
// شناسه از کجا؟	سرور	سرور	سرور	کلاینت (ایدمپوتنسی)
// خروجی	void	boolean	boolean	string | null


// cartService و orderService همسایه‌اند ولی قرینهٔ هم — یکی خوش‌بینِ برگشت‌پذیر، یکی بدبینِ برگشت‌ناپذیر. این تضاد بهترین اثباتِ کلِ لایه است: هیچ‌کدام از یک قالبِ مشترک نیامدند؛ هرکدام از فیزیکِ عملیاتِ خودش بیرون آمد — ارزان‌بودن یا گران‌بودن، برگشت‌پذیری یا نبودش.

// و باز، هر چهار سرویس روی یک سنگِ واحد ایستاده‌اند که حالا چهاربار مصرفش کرده‌ام و هنوز ننوشته‌امش — و این آخری یک طلبِ تازه هم اضافه کرد: قبلاً فقط فعل‌ها (get/post/patch/del) را خواستم، ولی این‌جا از http.post یک آرگومانِ سومِ { headers } هم خواستم تا Idempotency-Key را بفرستم. یعنی امضای http باید نه‌فقط فعل‌ها، که هدرهای سفارشیِ هر تماس را هم بپذیرد.

// پس مسیر از همیشه بدهکارتر است:

// services/http.ts — که حالا چهار سرویسِ واقعی رویش سوارند، و مجموعِ طلب‌هایشان دیگر یک امضای کامل است: union برگرداند، credentials: "include" بفرستد، چهار فعل داشته باشد، تلهٔ سراسریِ ۴۰۱ را بزند، و حالا آرگومانِ { headers } را هم بپذیرد. دیگر ذره‌ای ابهام نمانده که این فایل چه باید بکند — چون چهار مصرف‌کننده‌اش، خط‌به‌خط، قراردادش را تعریف کرده‌اند. http.ts دیگر یک صفحهٔ سفید نیست؛ یک جای خالیِ دقیقاً اندازه‌گیری‌شده است.

// برویم بالاخره services/http.ts را بسازیم؟ این‌بار نه یک سرویس، که چهار سرویس بی‌آن کامپایل نمی‌شوند — و دیگر واقعاً، واقعاً هیچ فایلی نمانده که بشود جلویش انداخت