// src/services/cartService.ts
import { http } from "./http";
import { useCartStore } from "../stores/cartStore";
import type { Cart } from "../types/cart";

/**
 * سرویسِ سبد = رهبرِ کنش‌های خوش‌بینانه.
 * برخلافِ productService (بخوان، بعد بنویس) و authService (صبورانه منتظر بمان)،
 * این‌جا ترتیب وارونه است: اول UI را عوض کن، بعد با سرور آشتی کن.
 * قرارداد: هر mutation یک snapshot می‌گیرد تا در شکست، rollback ممکن باشد.
 */

/** الگوی مشترکِ هر کنشِ خوش‌بینانه: عکس بگیر → خوش‌بین شو → آشتی/برگرد. */
async function optimistic(
  apply: () => void,
  request: () => Promise<{ ok: true; data: Cart } | { ok: false; error: unknown }>,
): Promise<boolean> {
  const store = useCartStore.getState();
  const snapshot = store.snapshot(); // عکسِ فوری، قبل از هر تغییر.

  apply();                            // حدسِ خوش‌بینانه — UI همین‌الان می‌پرد.

  const res = await request();
  if (res.ok) {
    store.setCart(res.data);          // جایگزینی با حقیقتِ سرور، نه صرفاً تأیید.
    return true;
  }

  store.restore(snapshot);            // شکست → دقیقاً همان حالتِ قبل باز می‌گردد.
  store.setCartError(res.error as any);
  return false;
}

/** افزودن به سبد — کلاسیک‌ترین کنشِ خوش‌بینانه. */
export async function addItem(productId: string, qty = 1): Promise<boolean> {
  const store = useCartStore.getState();
  return optimistic(
    () => store.addItemOptimistic(productId, qty),
    () => http.post<Cart>("/cart/items", { productId, qty }),
  );
}

/** تغییرِ تعداد — همان الگو؛ qty=0 را به حذف نگاشت نمی‌کنیم، کارِ استور است. */
export async function updateQty(productId: string, qty: number): Promise<boolean> {
  const store = useCartStore.getState();
  return optimistic(
    () => store.updateQtyOptimistic(productId, qty),
    () => http.patch<Cart>(`/cart/items/${productId}`, { qty }),
  );
}

/** حذفِ قلم — خوش‌بینانه ناپدید می‌شود، در شکست برمی‌گردد. */
export async function removeItem(productId: string): Promise<boolean> {
  const store = useCartStore.getState();
  return optimistic(
    () => store.removeItemOptimistic(productId),
    () => http.del<Cart>(`/cart/items/${productId}`),
  );
}

/**
 * بارگذاریِ سبد هنگامِ بوت — این یکی خوش‌بینانه **نیست**.
 * یک خواندنِ ساده است (مثلِ productService)، چون تغییری در کار نیست.
 * سبد سمتِ سرور زندگی می‌کند؛ هنگامِ ورود باید حقیقتِ سرور را بکشیم.
 */
export async function loadCart(): Promise<void> {
  const store = useCartStore.getState();
  store.setCartLoading();

  const res = await http.get<Cart>("/cart");

  if (res.ok) store.setCart(res.data);
  else store.setCartError(res.error);
}




















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — ترتیبِ وارونه، و rollback بهایش است: این چیزی است که cartService را از هر دو سرویسِ قبلی جدا می‌کند. productService شبکه‌اول بود، authService صبور بود؛ این‌جا UI-اول است. ولی خوش‌بینی یک قراردادِ اخلاقی می‌آورد که نمی‌شود شکستش: اگر جرأتِ تغییرِ زودهنگام داری، باید جرأتِ برگرداندنش را هم داشته باشی. پس snapshot() قبل از هر apply()، و restore() در هر شکست. سرویسی که خوش‌بین باشد ولی rollback نداشته باشد، سبدِ کاربر را با سرور ناهمگام رها می‌کند — بدترین باگِ خاموش.

// optimistic() یک هلپرِ داخلی — چون هر سه کنش دقیقاً یک رقص را می‌رقصند: افزودن، تغییرِ تعداد، و حذف، هر سه الگوی یکسان دارند: عکس بگیر، خوش‌بین شو، آشتی یا برگرد. به‌جای سه‌بار کپیِ این کوریوگرافی (و ریسکِ اینکه یکی‌شان restore را فراموش کند — دقیقاً همان اشتباهی که در سرویسِ قبلی دربارهٔ setError گفتم)، یک‌بار در optimistic() نوشتمش و سه کنش فقط apply و requestشان را تزریق می‌کنند. تفاوتِ کنش‌ها فقط در آن دو تابع است، نه در رقصِ دورشان.

// setCart(res.data) جایگزین می‌کند نه merge — ثمرهٔ «اعتماد کم» به کشِ سبد: یادت هست cartStore را «سرور آشتی‌دهنده، اعتماد کم» برچسب زدم؟ این خط همان است. حدسِ خوش‌بینانهٔ من ممکن است غلط باشد (موجودی نبود، قیمت پرید)، پس وقتی سرور جواب داد، کلِ سبد را با نسخهٔ او جایگزین می‌کنم. اگر merge می‌کردم، حدسِ غلطم را با حقیقتِ سرور قاطی می‌کردم. خوش‌بینی برای سرعتِ ادراکی است، نه برای حقیقت — حقیقت همیشه از آخرین پاسخِ سرور می‌آید.

// loadCart عمداً خوش‌بینانه نیست — چون خواندن است، نه کنش: جالبِ این فایل همین تضادِ درونی است: سه تابعِ اولش وارونه‌اند (UI-اول)، ولی loadCart به قالبِ productService برمی‌گردد (شبکه‌اول، setCartLoading). چون هنگامِ بوت تغییری رخ نمی‌دهد که بخواهیم خوش‌بین باشیم — فقط داریم حقیقتِ موجودِ سرور را می‌کشیم. همان درس: امضای تابع از جنسِ عملیات می‌آید (خواندن؟ کنش؟)، نه از فایلی که درونش است.

// همه boolean برمی‌گردانند (جز loadCart) — مثلِ login: کنش‌های سبد هم مثلِ login گاهی به کامپوننت خبر می‌خواهند بدهند — مثلاً «افزودن شکست خورد چون موجودی تمام شد» تا یک toast نشان داده شود. پس boolean. ولی loadCart مثلِ loadProducts مقدار برنمی‌گرداند، چون کامپوننت نتیجه را از استور می‌خواند. باز همان تفکیک: کنش خبر می‌دهد، خواندن فقط کش را پر می‌کند.

// چه چیزی این‌جا نیست: ادغامِ سبدِ مهمان با سبدِ کاربر هنگامِ ورود (یک گذارِ مجزا که شاید در authService یا این‌جا بنشیند، ولی منطقِ خاصِ خودش را دارد)، debounce ِ دکمهٔ +/− تعداد (کارِ کامپوننت — وگرنه هر کلیک یک درخواست)، محاسبهٔ جمع/مالیات (کارِ سرور، ما فقط res.data را نشان می‌دهیم)، و خودِ checkout (که به orderStore.prependNewOrder وصل می‌شود — سرویسِ دیگری). این فایل فقط رهبریِ کنش‌های خوش‌بینانهٔ سبد است.

// سرویسِ سوم — و این‌جا باید یک وسوسه را همان اول بکشم: «cartService هم یک سرویسِ کنشی است مثلِ authService، پس همان قالب.» نه. authService گذارهای هویت را می‌راند ولی صبور بود — setAuthLoading می‌زد و منتظرِ سرور می‌ماند. سبد اما یک جنسِ سومِ کامل است که هیچ‌کدام از دو سرویسِ قبلی نبودند: کنشِ خوش‌بینانه. کاربر روی «افزودن به سبد» می‌زند و انتظار دارد همین حالا — صفر میلی‌ثانیه — عدد بالای آیکنِ سبد بپرد، نه اینکه اسپینر ببیند و منتظرِ رفت‌وبرگشتِ شبکه بماند. این یعنی کلِ ترتیبِ سه‌گانهٔ آشنا (loading → fetch → success) این‌جا وارونه می‌شود: اول UI را عوض کن، بعد با سرور تأیید بگیر.

// قبل از کد، دو تصمیمِ بزرگ که این سرویس را از هر دو قبلی جدا می‌کنند:

// تصمیمِ بزرگِ اول — ترتیب وارونه است: mutate → network → reconcile/rollback. در productService شبکه قبل از تغییرِ استور بود (چون خواندن بود). این‌جا تغییرِ استور قبل از شبکه است (چون کنشِ خوش‌بینانه است). ولی خوش‌بینی یک بدهیِ پنهان دارد که باید صریح پرداختش کنم: اگر سرور رد کرد، باید حالتِ قبلی را برگردانم. پس قبل از هر تغییرِ خوش‌بینانه، یک عکسِ فوری از سبد می‌گیرم؛ اگر شبکه شکست خورد، دقیقاً همان عکس را باز می‌نشانم. خوش‌بینی بدونِ rollback فقط دروغ است.

// تصمیمِ بزرگِ دوم — پاسخِ سرور جایگزین می‌شود، نه اینکه صرفاً «تأیید» شود. یادت هست در cartStore گفتم اعتماد به کش کم است چون سرور آشتی‌دهنده است؟ این‌جا میوه‌اش را می‌بینی: وقتی سرور جواب داد، من حدسِ خوش‌بینانه‌ام را با پاسخِ او جایگزین می‌کنم، نه اینکه فرض کنم درست حدس زدم. چرا؟ چون سرور چیزهایی می‌داند که کلاینت نمی‌داند — موجودی تمام شده، قیمت عوض شده، تخفیف اعمال شده. حدسِ خوش‌بینانه فقط برای صفرکردنِ تأخیرِ ادراکی است؛ حقیقتِ نهایی همیشه از سرور می‌آید.


// خب، سه سرویس شد و حالا الگو در سه جنسِ متمایز اثبات شده — و این ردیفِ سوم نکته را کامل می‌کند:

// productService	authService	cartService
// جنسِ عملیات	خواندنِ داده	گذارِ هویت	کنشِ خوش‌بینانه
// ترتیب	شبکه → استور	استور(loading) → شبکه	استور → شبکه → آشتی
// در شکست	setError	setAuthError	restore(snapshot)
// اعتماد به حدسِ محلی	—	—	صفر (سرور جایگزین می‌کند)
// خروجی	void	boolean	boolean









// هر سه روی http سوارند، ولی چون یکی می‌خواند، یکی هویت می‌راند، و یکی خوش‌بینانه تغییر می‌دهد، سه ترتیبِ کاملاً متفاوت گرفتند. آن ستونِ سومِ «ترتیبِ وارونه + rollback» چیزی است که هیچ قالبِ کپی‌شده‌ای نمی‌توانست بدهد — از ماهیتِ کنشِ خوش‌بینانه آمد، نه از یک الگوی مشترک.

// و باز، هر سه سرویس روی یک چیزِ واحد ایستاده‌اند که حالا سه‌بار مصرفش کرده‌ام و هنوز ننوشته‌امش: آن http که union برمی‌گرداند، که credentials: "include" می‌فرستد (تا کوکیِ نشستِ سبد برود)، و حالا چیزِ تازه‌ای هم ازش خواستم — http.patch و http.del، نه فقط get/post. یعنی این فایل نه‌تنها به http وابسته است، که به کاملیِ سطحِ فعل‌هایش هم وابسته شد.

// پس مسیر از همیشه فوری‌تر است:

// services/http.ts — که حالا سه سرویسِ واقعی رویش سوارند و این آخری حتی چهار فعلِ کاملش (get/post/patch/del) را طلب می‌کند. دیگر نه ایده است نه ضرورتِ آینده؛ سه فایلِ مشخص همین حالا صدایش می‌زنند، به union-اش تکیه می‌کنند، و بدونش هیچ‌کدام کامپایل نمی‌شوند. آن snapshot/restore که این‌جا فرض گرفتم به cartStore برمی‌گردد — ولی آن http.patch که فرض گرفتم، جایی جز http.ts ندارد که تعریف شود.

// برویم بالاخره services/http.ts را بسازیم و زیرِ پای هر سه سرویس را یک‌جا سفت کنیم؟ این‌بار دیگر واقعاً هیچ فایلِ دیگری نمانده که بشود بهانه‌اش کرد. 