import { http } from "./http";
import { useWishlistStore } from "../stores/wishlistStore";
import type { WishlistItem } from "../types/wishlist";

/**
 * سرویسِ لیستِ علاقه = خوش‌بینِ پُراعتماد.
 * همسایهٔ cartService و هم‌جنسِ خوش‌بینِ آن، ولی درست از یک نقطه قرینه می‌شود:
 *   cartService → اعتمادِ صفر، سرور جایگزین می‌کند (موجودی/قیمت/تخفیف).
 *   wishlistService → اعتمادِ بالا، حدسِ محلی خودش حقیقت است (فقط عضویت).
 * قرارداد: یک toggleِ دوحالته، خود-ترمیم؛ پاسخِ سرور «تأیید» است نه «منبعِ حقیقت».
 */

/** آیا این محصول همین‌الان در لیست هست؟ منبعِ خوش‌بینی و rollback. */
function isIn(productId: string): boolean {
  return useWishlistStore.getState().ids.has(productId);
}

/**
 * toggleِ علاقه — تنها ژستِ این سرویس، دوحالته و خوش‌بینانه.
 * ترتیب مثلِ سبد وارونه است (UI اول)، ولی سرور را جایگزین نمی‌کنیم:
 * حدسِ محلی نهایی است، چون آیتمِ علاقه هیچ حقیقتِ سروری‌ای حمل نمی‌کند.
 */
export async function toggle(productId: string): Promise<boolean> {
  const store = useWishlistStore.getState();

  const wasIn = isIn(productId);   // عکسِ فوریِ همین یک بیت — کلِ چیزی که برای rollback لازم است.
  const willAdd = !wasIn;

  // حدسِ خوش‌بینانه — قلب همین‌الان می‌پرد.
  if (willAdd) store.addOptimistic(productId);
  else store.removeOptimistic(productId);

  const res = willAdd
    ? await http.post<WishlistItem>("/wishlist/items", { productId })
    : await http.del<void>(`/wishlist/items/${productId}`);

  if (res.ok) return true; // «تأیید» شد؛ چیزی برای جایگزینی نیست — حدسم خودش حقیقت بود.

  // شکست → فقط اگر حالت هنوز همان حدسِ من باشد برگردان.
  // اگر کلیکِ تازه‌تری وسط رسیده و بیت را عوض کرده، دست نمی‌زنیم:
  // toggle خود-ترمیم است، و rollbackِ کور یک مسابقه می‌سازد.
  if (isIn(productId) === willAdd) {
    if (wasIn) store.addOptimistic(productId);
    else store.removeOptimistic(productId);
  }
  store.setError(res.error);
  return false;
}

/**
 * بارگذاریِ لیست هنگامِ بوت — این یکی خوش‌بینانه **نیست**، دقیقاً مثلِ loadCart.
 * یک خواندنِ ساده است؛ تغییری در کار نیست که بخواهیم خوش‌بین باشیم.
 * لیست سمتِ سرور زندگی می‌کند؛ هنگامِ ورود حقیقتِ موجود را می‌کشیم.
 */
export async function loadWishlist(): Promise<void> {
  const store = useWishlistStore.getState();
  store.setLoading();

  const res = await http.get<WishlistItem[]>("/wishlist");

  if (res.ok) store.setItems(res.data);
  else store.setError(res.error);
}






















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — همان قالبِ خوش‌بینانه، ولی ستونِ «اعتماد» وارونه، و همه‌چیز از همان‌جا می‌ریزد: cartService و wishlistService تا مرزِ کپی‌شدن به هم شبیه‌اند — هر دو خوش‌بین، هر دو UI-اول، هر دو snapshot/rollback. ولی یک تفاوت (اعتماد به حدسِ محلی: صفر در برابرِ بالا) مثلِ کلیدی سه قفلِ دیگر را می‌گرداند: چون اعتماد بالاست، سرور جایگزین نمی‌کند؛ چون جایگزین نمی‌کند، مسابقهٔ toggle خود‌به‌خود خنثی می‌شود؛ چون آیتم حقیقتی حمل نمی‌کند، شکست بی‌خطرترینِ لایه است. اگر optimistic()ِ سبد را کورکورانه کپی کرده بودم، setCart(res.data)اش پاسخِ دیرآمده را می‌نشاند و دقیقاً همان مسابقه‌ای را می‌ساخت که این‌جا رایگان حل شد.

// setError هست ولی معنایش «تأیید-جایگزین» نیست: برخلافِ سبد که موفقیت یعنی «نسخهٔ سرور را بگیر»، این‌جا موفقیت یعنی «هیچ کارِ اضافه‌ای نکن» — حدس درست بود. این ظریف‌ترین تفاوتِ رفتاری است: در سبد شاخهٔ res.ok پُرترین شاخه بود (setCart)، این‌جا خالی‌ترین است (return true). موفقیتِ یک عملیاتِ پُراعتماد، سکوت است.

// rollbackِ شرطی (isIn(productId) === willAdd) — قلبِ ضدِ مسابقه: این تنها جای کلِ شش سرویس است که rollback بی‌قید‌وشرط نیست. سبد بی‌قیدشرط restore می‌کرد چون کنش‌هایش متقارن و کند نبودند؛ toggle سریع و دوحالته است، پس پیش از بازگرداندن می‌پرسم «آیا بیت هنوز همان است که من گذاشتم؟». اگر کلیکِ تازه‌تری superseded کرده، restoreِ کور خودش یک باگ می‌ساخت. خود-ترمیمیِ toggle یعنی گاهی بهترین rollback، هیچ rollback است.

// ids: Set نه آرایه — چرا استور این شکلی است، این‌جا معلوم می‌شود: isIn باید در O(1) جواب دهد، چون هر کارتِ محصول در فهرست می‌پرسد «آیا این در علاقه‌مندی‌هاست؟» تا قلبش را پُر یا خالی بکشد. اگر آرایه بود، هر رندرِ فهرست یک includes خطی می‌شد. این همان الگوی همیشگی: شکلِ استور از الگوی خواندنِ کامپوننت می‌آید، و سرویس فقط رویش می‌نویسد.

// این سرویس از http هیچ چیزِ تازه‌ای نمی‌خواهد — و این خودش خبر است: پنج سرویسِ قبل هرکدام یک شرطِ نو روی http گذاشتند (union، چهار فعل، هدرِ سفارشی، FormData، تلهٔ ۴۰۱). این ششمی؟ فقط get/post/delِ ساده، بدنهٔ JSON، بی‌هدرِ خاص، تسلیمِ تلهٔ ۴۰۱. یعنی قراردادِ http دیگر اشباع شده: مصرف‌کنندهٔ تازه چیزی به آن اضافه نمی‌کند. این اولین نشانهٔ محکم است که مشخصات هم‌گرا شده، نه اینکه هنوز باز باشد.

// چه چیزی این‌جا نیست: «انتقال به سبد» (یک گذارِ دو-استوره‌ای که علاقه→سبد را پل می‌زند، درست مثلِ checkout که سبد→سفارش را پل زد — منطقِ خودش را دارد و شاید همان‌جا بنشیند)، ادغامِ لیستِ مهمان با کاربر هنگامِ ورود (همان گذارِ مبهمی که در سبد هم کنار گذاشتم)، اعلانِ «موجود شد / ارزان شد» برای آیتم‌های علاقه (کارِ سرور و نوتیفیکیشن، نه این‌جا)، و اشتراک‌گذاریِ عمومیِ لیست (سرویس و مسیرِ خودش). این فایل فقط toggleِ عضویت و خواندنِ لیست است.




// سرویسِ ششم — و این‌جا وسوسه از هر پنج بارِ قبل شبیه‌تر به حق است، برای همین خطرناک‌تر: wishlistService انگار مو‌به‌مو همان cartService است. باز افزودن، باز حذف، باز خوش‌بینانه، باز آیکنی که باید همین‌حالا بپرد (این‌بار قلب، نه عددِ سبد). ذهن با اطمینان می‌گوید: «این دیگر واقعاً کپیِ سبد است — همان optimistic() را بیاور، endpointها را عوض کن، تمام.» و باز نه. لیستِ علاقه‌مندی خوش‌بینانه هست — تا این‌جا با سبد یکی‌اند — ولی درست از همان نقطه‌ای که خوش‌بینیِ سبد بدهیِ پنهانش را رو کرد (اعتمادِ صفر، سرور جایگزین می‌کند)، این‌جا قرینه می‌شود: خوش‌بینیِ لیستِ علاقه، اعتمادش بالاست. و همین یک تفاوت، مثلِ یک سنگِ اول در دومینو، سه تصمیمِ دیگر را هم برمی‌گرداند.

// قبل از کد، سه تصمیمِ بزرگ که این سرویس را از همسایهٔ فریبنده‌اش cartService جدا می‌کنند:

// تصمیمِ بزرگِ اول — خوش‌بین، ولی این‌بار اعتماد به حدسِ محلی بالاست، پس سرور جایگزین نمی‌کند. در cartService مهم‌ترین خط setCart(res.data) بود: حدسم را دور می‌ریختم و نسخهٔ سرور را می‌نشاندم، چون سرور آشتی‌دهنده بود — موجودی، قیمت، تخفیف. ولی یک آیتمِ علاقه‌مندی هیچ حقیقتِ سروری‌ای حمل نمی‌کند: نه موجودی دارد، نه قیمت، نه تخفیف — فقط عضویتِ یک productId در یک مجموعه است، یک بیت: هست یا نیست. پس وقتی سرور «۲۰۰» گفت، چیزی برای جایگزینی نیست؛ حدسِ خوش‌بینانه‌ام خودش حقیقت بود. این‌جا خوش‌بینی هم تأخیر را صفر می‌کند، هم نهایی است.

// تصمیمِ بزرگِ دوم — این یک toggle است، نه دو کنشِ متقارن؛ و toggle یک مسابقهٔ خاصِ خودش دارد. سبد سه فعلِ مجزا داشت (افزودن/تغییرِ تعداد/حذف). لیستِ علاقه یک ژستِ دوحالته دارد: کلیکِ روی قلب. و ژستِ دوحالته یک باگِ کلاسیک می‌آورد که سبد نداشت: کلیکِ سریعِ پیاپی. کاربر قلب را روشن/خاموش/روشن می‌کند؛ سه درخواست در راه‌اند و پاسخ‌ها ممکن است به‌هم‌ریخته برسند (POSTِ اول بعد از DELETEِ دوم برگردد). و این‌جا تصمیمِ اول میوه‌اش را می‌دهد: چون سرور را جایگزین نمی‌کنم، پاسخِ دیرآمده نمی‌تواند حالتِ تازه‌تر را خراب کند — همان بی‌اعتمادی به پاسخِ سرور که تصمیمِ اول بود، خودش مسابقه را خنثی می‌کند. فقط می‌ماند rollbackِ شکست، که باید بپرسد «آیا حدسم هنوز حالتِ فعلی است؟» پیش از بازگرداندن.

// تصمیمِ بزرگِ سوم — شکست این‌جا نرم‌ترین شکستِ کلِ لایه است، ولی rollback باز هم واجب می‌ماند. طیفِ ما یک سر داشت checkout (برگش ولی با ظرافتی که toggle طلب می‌کند: خودِ toggle خود-ترمیم است، چون کلیکِ بعدی دوباره هم‌گام می‌کند


// خب، شش سرویس شد و جدول به کامل‌ترین شکلش رسید — و ردیفِ ششم دقیقاً همان‌جایی می‌نشیند که فکر می‌کردی تکراری است، ولی یک ستون را وارونه می‌کند:

