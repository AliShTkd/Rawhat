
// src/services/authService.ts
import { http } from "./http";
import { useUserStore } from "../stores/userStore";
import type { User, Credentials, RegisterPayload } from "../types/user";

/**
 * سرویسِ auth = رهبرِ چرخهٔ عمرِ هویت.
 * برخلافِ productService، این‌جا کشی نیست — فقط گذارهای نشست:
 * login / register / logout / و بازیابیِ نشست هنگامِ بوت.
 * منبعِ حقیقتِ نشست، کوکیِ HttpOnly است (تصمیمِ userStore)؛
 * پس هیچ توکنی این‌جا ذخیره نمی‌شود — سرور با Set-Cookie می‌نشاندش.
 */

/**
 * ورود. یک کنشِ تغییردهنده است، نه خواندن — پس هرگز کش‌آگاه نیست.
 * موفقیت: کوکی نشسته و پروفایل برمی‌گردد → setUser.
 */
export async function login(credentials: Credentials): Promise<boolean> {
  const store = useUserStore.getState();
  store.setAuthLoading();

  const res = await http.post<User>("/auth/login", credentials);

  if (res.ok) {
    store.setUser(res.data);
    return true;
  }
  // خطای ورود (۴۰۱ = رمزِ غلط) این‌جا واقعاً خطاست — برخلافِ bootstrap.
  store.setAuthError(res.error);
  return false;
}

/**
 * ثبت‌نام. مثلِ login یک گذارِ نشست است؛ سرور معمولاً همان‌جا
 * کوکی را هم می‌نشاند (ثبت‌نام = ورودِ خودکار).
 */
export async function register(payload: RegisterPayload): Promise<boolean> {
  const store = useUserStore.getState();
  store.setAuthLoading();

  const res = await http.post<User>("/auth/register", payload);

  if (res.ok) {
    store.setUser(res.data);
    return true;
  }
  store.setAuthError(res.error);
  return false;
}

/**
 * خروج. نکتهٔ ظریف: حتی اگر شبکه شکست بخورد، کاربر باید
 * به‌صورتِ محلی خارج شود. «خروجِ نیمه‌کاره» بدترین حالت است —
 * پس clearUser بی‌قید‌وشرط، چه سرور جواب بدهد چه ندهد.
 */
export async function logout(): Promise<void> {
  const store = useUserStore.getState();

  // به سرور خبر می‌دهیم تا کوکی را باطل کند — ولی نتیجه‌اش را گرو نمی‌گیریم.
  await http.post<void>("/auth/logout", undefined);

  // پاک‌سازیِ محلی همیشه اتفاق می‌افتد. UI نباید در حالتِ «شاید وارد» گیر کند.
  store.clearUser();
}

/**
 * بازیابیِ نشست هنگامِ بوتِ برنامه — گذارِ چهارمِ فراموش‌شده.
 * این‌جا ۴۰۱ **خطا نیست**، یعنی «مهمان». تنها جایی که تلهٔ سراسریِ
 * ۴۰۱ باید به یک حالتِ عادی ترجمه شود، نه به setError.
 */
export async function fetchCurrentUser(): Promise<void> {
  const store = useUserStore.getState();
  store.setAuthLoading();

  const res = await http.get<User>("/auth/me");

  if (res.ok) {
    store.setUser(res.data);
    return;
  }

  // ۴۰۱/۴۰۳ → مهمان، یک حالتِ معتبر و ساکت.
  if (res.error.status === 401 || res.error.status === 403) {
    store.clearUser();
    return;
  }

  // فقط خطاهای واقعی (۵۰۰، شبکه) به‌عنوانِ خطا نشان داده می‌شوند.
  store.setAuthError(res.error);
}
















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — ۴۰۱ دو معنای متفاوت دارد، و سرویس تنها جایی است که تفکیکشان می‌کند: در http یک تلهٔ سراسریِ ۴۰۱ کاشتیم که clearUser می‌زند (نشستِ منقضی → بیرونت کن). ولی در fetchCurrentUser، ۴۰۱ اصلاً منقضی‌شدن نیست — «از اول وارد نشده بودی» است، یک حالتِ عادیِ مهمان. و در login، همان ۴۰۱ یعنی «رمز غلط» — یک خطای واقعی که باید دیده شود. یک کدِ وضعیت، سه معنا، و هر سه این‌جا آگاهانه از هم جدا شده‌اند. این دقیقاً همان چیزی است که نمی‌شد به کامپوننت سپرد.

// logout نتیجهٔ شبکه را گرو نمی‌گیرد — clearUser بی‌قیدوشرط: این ظریف‌ترین تصمیمِ رفتاری است. اگر خروج را مشروط به موفقیتِ سرور می‌کردم، یک قطعیِ شبکه کاربر را در حالتِ «فکر می‌کنم واردم ولی مطمئن نیستم» حبس می‌کرد — بدترین حالتِ ممکن برای auth. پس await می‌کنم که به سرور خبر برسد (کوکی باطل شود)، ولی clearUser را بعد از آن بی‌شرط صدا می‌زنم. خروج باید همیشه از دیدِ کاربر قطعی باشد.

// هیچ توکنی این‌جا ذخیره نمی‌شود — ثمرهٔ تصمیمِ کوکیِ userStore: یادت هست در userStore گفتم منبعِ حقیقتِ نشست، کوکیِ HttpOnly است نه حافظهٔ JS؟ این‌جا میوه‌اش را می‌بینی: پاسخِ login فقط پروفایل (User) برمی‌گرداند، نه توکن. سرور با Set-Cookie نشست را می‌نشاند و http با credentials: "include" در هر درخواستِ بعدی خودکار می‌فرستدش. سرویس اصلاً نمی‌داند توکن کجاست — و همین امن‌ترین حالت است (JS نمی‌تواندش بدزدد).

// login/register مقدارِ boolean برمی‌گردانند — بقیهٔ سرویس‌ها void: یک ناهماهنگیِ عمدی. loadProducts هیچ برنمی‌گرداند چون کامپوننت نتیجه را از استور می‌خواند. ولی login باید به کامپوننتِ فرم بگوید «موفق شدی یا نه» تا همان‌جا تصمیمِ ناوبری بگیرد (redirect به داشبورد در موفقیت، ماندن روی فرم در شکست). این تفاوت چون login یک لحظهٔ گذار در جریانِ کاربر است، نه صرفاً پرکردنِ یک کش.

// fetchCurrentUser گذارِ چهارمِ نامرئی است — و بدونش کلِ auth می‌شکند: سه گذارِ آشکار (login/logout/register) را همه می‌بینند، ولی این یکی را اغلب فراموش می‌کنند: وقتی کاربرِ قبلاً‌واردشده صفحه را رفرش می‌کند، حافظهٔ JS صفر می‌شود ولی کوکی هنوز هست. بدونِ این تابع که هنگامِ بوت «من کی‌ام؟» را بپرسد، هر رفرش کاربر را ظاهراً بیرون می‌انداخت. این پلِ بینِ «کوکیِ ماندگار» و «حافظهٔ فرّار» است.

// چه چیزی این‌جا نیست: فراخوانیِ fetchCurrentUser هنگامِ بوت (کارِ یک <AuthBootstrap> یا هوک در ریشهٔ برنامه)، نگه‌داریِ فرمِ ورود و اعتبارسنجی‌اش (کارِ کامپوننت)، رفرشِ خودکارِ توکن (اگر معماری‌اش را داشته باشیم، در http می‌نشیند نه این‌جا)، و مدیریتِ نقش/دسترسی. این فایل فقط رهبریِ چرخهٔ عمرِ هویت است.

// سرویسِ دوم — و این‌جا باید یک وسوسه را همان اول رد کنم: «authService هم مثلِ productService است، فقط endpointهایش فرق دارد.» نه. productService دربارهٔ خواندنِ کش‌آگاهانهٔ داده بود؛ authService دربارهٔ چیزِ کاملاً دیگری است — چرخهٔ عمرِ هویت. این‌جا اصلاً کشی در کار نیست که ازش بپرسیم؛ این‌جا گذارهای حالتِ یک نشست است: ورود، خروج، ثبت‌نام، و آن گذارِ نامرئیِ چهارم که همه فراموشش می‌کنند — «بازیابیِ نشست هنگامِ باز شدنِ برنامه». پس قالبِ productService (کش‌آگاهی → loading → fetch → نگاشت) این‌جا نصفش اصلاً صدق نمی‌کند.

// قبل از کد، دو تصمیمِ بزرگ که این سرویس را از قبلی جدا می‌کنند:

// تصمیمِ بزرگِ اول — auth هرگز کش‌آگاه نیست، و این عمدی است. در productService گفتم «قبل از شبکه از کش بپرس». این‌جا برعکسِ محض: هر ورود به شبکه می‌رود، هر خروج به شبکه می‌رود. چرا؟ چون login یک خواندن نیست، یک کنشِ تغییردهنده است — «شاید کاربر قبلاً وارد شده» یک بهینه‌سازی نیست، یک باگِ امنیتی است. کش‌آگاهی برای دادهٔ ثابت معنا دارد، نه برای گذارِ هویت. پس اولین نیمهٔ الگوی سرویسِ قبلی این‌جا عمداً حذف می‌شود.

// تصمیمِ بزرگِ دوم — ۴۰۱ در fetchCurrentUser خطا نیست، یک پاسخِ معتبر است. این ظریف‌ترین نکتهٔ کلِ فایل است. وقتی برنامه باز می‌شود و می‌پرسیم «من کی‌ام؟»، پاسخِ ۴۰۱ یعنی «تو وارد نشده‌ای» — که یک حالتِ کاملاً عادی است، نه یک خطا. اگر این را مثلِ بقیهٔ ۴۰۱ها به setError بدهم، هر بازدیدکنندهٔ مهمان یک پیامِ خطای قرمز می‌بیند. پس این یک تابع باید ۴۰۱ را نه به‌عنوانِ شکست، که به‌عنوانِ «مهمان» ترجمه کند. این تنها جایی است که تلهٔ سراسریِ ۴۰۱ی که در http کاشتیم باید دور زده شود.


// خب، دو سرویس شد و حالا الگو در دو جنسِ متفاوت اثبات شده — و این تضاد آموزنده است:

// productService	authService
// جنسِ عملیات	خواندنِ داده	گذارِ هویت
// کش‌آگاه؟	✅ بله	❌ هرگز
// ۴۰۱ یعنی	خطا	گاهی «مهمان»، گاهی «رمز غلط»
// خروجی به کامپوننت	void (از استور بخوان)	boolean (تصمیمِ ناوبری)
// خطا همیشه دیده شود؟	بله	نه (bootstrap ساکت است)



// هر دو «سرویس»اند و هر دو روی http سوارند، ولی چون یکی داده می‌آورد و دیگری هویت می‌راند، دو رفتارِ کاملاً متفاوت گرفتند. باز همان درسِ همیشگی، این‌بار یک لایه بالاتر: نه‌فقط ساختارِ استور، که حتی امضای سرویس هم از ماهیتِ کاری که می‌کند می‌آید، نه از یک قالبِ کپی‌شده.

// و هر دو سرویس، دقیقاً روی یک چیز ایستاده‌اند که دو بار حالا مصرفش کردیم و هنوز ننوشتیمش: آن http که union برمی‌گرداند، که credentials: "include" می‌فرستد، و آن تلهٔ سراسریِ ۴۰۱ که در این فایل اولین‌بار به‌صراحت بهش اشاره کردم («تلهٔ سراسری باید دور زده شود») — بدونِ اینکه هنوز وجود داشته باشد که دور زده شود.

// پس مسیر روشن‌تر از همیشه است:

// services/http.ts — که حالا دو سرویسِ واقعی رویش نوشته شده و هیچ‌کدام بدونش کامپایل نمی‌شوند. دیگر بحثِ «استورها منتظرند» نیست؛ دو فایلِ مشخص (productService, authService) همین حالا http.get/http.post را صدا می‌زنند، به res.ok/res.error تکیه می‌کنند، و authService حتی به رفتارِ داخلیِ ۴۰۱‌اش وابسته است. آن تلهٔ ۴۰۱ که به clearUser وصل می‌شود، دیگر یک ایده نیست — یک قراردادی است که این فایل صریح فرض کرد.

// برویم services/http.ts را بسازیم و بالاخره زیرِ پای این دو سرویس را سفت کنیم؟