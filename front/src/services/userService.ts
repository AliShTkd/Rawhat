
// src/services/userService.ts
import { http } from "./http";
import { setUserActions } from "../stores/userStore";
import type { User, ProfilePatch, PasswordChange } from "../types/user";

/**
 * سرویسِ کاربر = ویرایشگرِ هویتِ ازپیش‌موجود.
 * همسایهٔ authService و هم‌استورِ آن، ولی قرینه‌اش:
 *   authService → وجودِ نشست (تولد/مرگ/بازیابی).
 *   userService → محتوای هویت (زندگیِ روزمره)، بی‌آنکه نشست را لمس کند.
 * قرارداد: loadingِ این‌جا «در حالِ ذخیره» است، نه «در حالِ احرازِ هویت»
 * — دو پرچمِ جدا در userStore، تا اپ اشتباهاً فکر نکند کاربر دارد عوض می‌شود.
 */

/**
 * ویرایشِ پروفایل — یک تغییرِ *قابل‌نمایش*، پس در موفقیت setUser.
 * PATCH چون تغییرِ جزئی است (فقط فیلدهای عوض‌شده)، نه جایگزینیِ کاملِ کاربر.
 * سرور آشتی‌دهنده است (ایمیل را lowercase می‌کند، آدرسِ آواتار را بازمی‌نویسد)،
 * پس res.data را جایگزین می‌کنیم، نه patchِ محلی را.
 */
export async function updateProfile(patch: ProfilePatch): Promise<boolean> {
  setUserActions.setSaving();

  const res = await http.patch<User>("/users/me", patch);

  if (res.ok) {
    setUserActions.setUser(res.data);
    return true;
  }
  setUserActions.setSaveError(res.error);
  return false;
}

/**
 * تغییرِ رمز — یک تغییرِ *نامرئی*: هیچ‌چیزِ روی صفحه عوض نمی‌شود.
 * پس عمداً setUser نمی‌زند؛ فقط موفقیت/شکست را گزارش می‌کند.
 * سرور نشستِ فعلی را زنده نگه می‌دارد (کوکی را دوباره می‌نشاند)،
 * پس اینجا clearUser هم نمی‌کنیم — کاربر همان‌جا که هست می‌ماند.
 */
export async function changePassword(payload: PasswordChange): Promise<boolean> {
  setUserActions.setSaving();

  const res = await http.post<void>("/users/me/password", payload);

  if (res.ok) {
    setUserActions.clearSaving();
    return true;
  }
  setUserActions.setSaveError(res.error);
  return false;
}

/**
 * بارگذاریِ آواتار — تنها تماسی که بدنه‌اش JSON نیست، بلکه multipart است.
 * فایل را در FormData می‌گذاریم و به http می‌سپاریم؛ http نباید
 * Content-Type: application/json را تحمیل کند وقتی بدنه FormData است.
 * موفقیت → آدرسِ تازهٔ آواتار در res.data، پس setUser (قابل‌نمایش است).
 */
export async function uploadAvatar(file: File): Promise<boolean> {
  setUserActions.setSaving();

  const form = new FormData();
  form.append("avatar", file);

  const res = await http.post<User>("/users/me/avatar", form);

  if (res.ok) {
    setUserActions.setUser(res.data);
    return true;
  }
  setUserActions.setSaveError(res.error);
  return false;
}




















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — دو سرویس روی یک استور، و مرزشان دلیل است نه داده: authService و userService هر دو useUserStore را می‌نویسند، ولی این هم‌استوری آن‌ها را یکی نمی‌کند. یکی وجود را می‌راند (نشست هست یا نیست)، دیگری محتوا را (نامِ این هویت چیست). قرینهٔ آموزندهٔ ردیفِ قبل است: orderService یک سرویس بود که دو استور را می‌راند؛ این‌جا دو سرویس‌اند که یک استور را می‌رانند. در هر دو مورد، مرز از مسئولیت می‌آید نه از شمارشِ استورها. اگر ادغامشان می‌کردم، authService که باید کوچک و مقدس بماند (فقط تولد/مرگ) با ده‌ها تابعِ ویرایشِ پروفایل آماس می‌کرد.

// setSaving جدا از setAuthLoading — همان یک استور، دو معنای loading: این ظریف‌ترین ثمرهٔ جداسازی است. «در حالِ احرازِ هویت» یک حالتِ سراسری و ترسناک است (شاید کاربر عوض شود، شاید گاردها فعال شوند)؛ «در حالِ ذخیرهٔ پروفایل» یک حالتِ محلی و بی‌خطر است (فقط یک دکمهٔ «ذخیره» اسپینر می‌گیرد). اگر یک پرچمِ مشترک بود، ذخیرهٔ یک بیو ممکن بود کلِ اپ را به حالتِ «هویت نامعلوم» ببرد. یک استور می‌تواند چند نوع loading داشته باشد، و درهم‌ریختنشان یک باگِ نامرئیِ UX است.

// changePassword عمداً به استور دست نمی‌زند — چون تغییرش نامرئی است: بهترین نمونهٔ «امضا و رفتار از ماهیتِ عملیات می‌آید». updateProfile و uploadAvatar هر دو setUser می‌زنند چون چیزی دیدنی عوض شده (نام، عکس). ولی رمز روی صفحه نیست؛ پس setUser زدن فقط یک User بی‌تغییر را بیهوده باز می‌نشاند. سه تابع در یک فایل، و دو رفتارِ متفاوت با استور — چون دو تا تغییرِ دیدنی می‌کنند و یکی تغییرِ نادیدنی.

// ۴۰۱ این‌جا تله را دور نمی‌زند — قرینهٔ صریحِ fetchCurrentUser: این چهارمین معنای همان کدِ وضعیت است و جالب‌ترین جفتش با authService. آن‌جا ۴۰۱ را دستی گرفتم و به «مهمان» ترجمه‌اش کردم (تله را دور زدم). این‌جا هیچ if (status === 401)ای نمی‌نویسم — عمداً — چون کاربرِ در‌حالِ‌ویرایش که ۴۰۱ می‌گیرد یعنی واقعاً نشستش پرید، و این دقیقاً کاری است که تلهٔ سراسری برایش ساخته شد. گاهی درست‌ترین کارِ سرویس، دست‌نزدن است و سپردنش به قراردادِ http.

// uploadAvatar بدنهٔ غیر-JSON می‌فرستد — طلبِ تازه‌ای از http: هر سرویس یک چیزِ نو از http خواست؛ این‌بار: بدنه همیشه JSON نیست. وقتی FormData می‌فرستم، http نباید Content-Type: application/json را تحمیل کند (مرورگر باید خودش multipart/form-data را با boundary بنشاند). پس امضای http باید بدنهٔ FormData را تشخیص دهد و از serialize/Content-Typeِ خودکار صرفِ‌نظر کند. یک شرطِ دیگر که این فایل روی قراردادِ http گذاشت.

// چه چیزی این‌جا نیست: حذفِ حساب (تخریبِ هویت — قرینهٔ logout است و به مرزِ authService/clearUser نزدیک‌تر، نه ویرایشِ روزمره)، اتصالِ حساب‌های اجتماعی (OAuth، جریانِ ری‌دایرکتِ خودش)، مدیریتِ آدرس‌های ارسال (شاید استور و سرویسِ خودش، چون فهرست‌محور است نه پروفایلِ تک)، اعتبارسنجیِ فرم و قوّتِ رمز (کارِ کامپوننت)، و برشِ سمتِ‌کلاینتِ آواتار (کارِ کامپوننت پیش از آپلود). این فایل فقط ویرایشِ محتوایِ یک هویتِ ازپیش‌موجود است.


// سرویسِ پنجم — و این‌جا باید موذی‌ترین وسوسهٔ کلِ لایه را همان اول خفه کنم، چون این‌بار وسوسه از جنسِ «مرزِ مبهم» است، نه «قالبِ کپی‌شده»: «userService که همان authService است دیگر — هر دو دربارهٔ کاربرند، هر دو روی userStore می‌نویسند؛ پس این توابع را ببر توی authService و یک فایل کم کن.» نه. این‌که دو سرویس روی یک استور می‌نویسند دلیلِ ادغامشان نیست — دلیلِ این است که باید چرایشان را با وسواس از هم جدا کنم. authService مالکِ وجودِ نشست است: نشست را به دنیا می‌آورد (login/register)، از دنیا می‌برد (logout)، و هنگامِ بوت پیدایش می‌کند (fetchCurrentUser). userService اصلاً به وجودِ نشست دست نمی‌زند — نشست را مفروض می‌گیرد و محتوای آن هویتِ ازپیش‌موجود را ویرایش می‌کند. یکی تولد و مرگ است، دیگری زندگیِ روزمره. همان userStore، دو نویسنده، دو دلیلِ کاملاً متفاوت.

// قبل از کد، سه تصمیمِ بزرگ که این سرویس را از هر چهار قبلی — و مخصوصاً از همسایهٔ خطرناکش authService — جدا می‌کنند:

// تصمیمِ بزرگِ اول — دو نویسنده روی یک استور، ولی حالتِ loadingشان یکی نیست. authService وقتی کار می‌کند setAuthLoading می‌زند — یعنی «کلِ برنامه در حالتِ نامعلومِ هویت است، شاید کاربر عوض شود». اگر userService هم برای ذخیرهٔ یک نامِ نمایشیِ ویرایش‌شده همان setAuthLoading را می‌زد، فاجعهٔ ادراکی بود: کلِ اپ فکر می‌کرد دارد دوباره احراز هویت می‌شود، شاید گاردهای مسیر کاربر را به صفحهٔ ورود می‌پراندند — فقط چون کسی می‌خواست بیوگرافی‌اش را عوض کند. پس userStore یک پرچمِ مجزا برای «در حالِ ذخیره» دارد (setSaving)، جدا از پرچمِ «در حالِ احرازِ هویت». یک استور، دو نوع loadingِ معنایی.

// تصمیمِ بزرگِ دوم — هر mutation یک‌جور با استور حرف می‌زند؛ بعضی setUser می‌کنند، بعضی به استور اصلاً دست نمی‌زنند. این ظریف‌ترین نکتهٔ فایل است. updateProfile وقتی موفق شد باید کاربرِ استور را با نسخهٔ تازه جایگزین کند (نام عوض شده، UI باید فوراً نشانش دهد). ولی changePassword وقتی موفق شد هیچ‌چیزِ قابل‌نمایشی عوض نشده — رمز که روی صفحه نیست. پس changePassword عمداً setUser نمی‌زند؛ فقط boolean برمی‌گرداند و تمام. اگر کورکورانه یک قالبِ «موفقیت → setUser» می‌ساختم، changePassword مجبور می‌شد یک User بی‌تغییر را بی‌دلیل دوباره بنشاند. ماهیتِ هر تغییر تعیین می‌کند که آیا اصلاً به استور دست بزند یا نه.

// تصمیمِ بزرگِ سوم — ۴۰۱ این‌جا دوباره معنای تازه‌ای دارد: «نشستت واقعاً منقضی شد» — و برخلافِ fetchCurrentUser، این‌جا تله را دور نمی‌زنم. یادت هست در authService گفتم fetchCurrentUser تنها جایی است که تلهٔ سراسریِ ۴۰۱ باید دور زده شود (چون آن‌جا ۴۰۱ = مهمان)؟ این‌جا دقیقاً برعکس: کاربر آشکارا واردِ سیستم بوده (داشته پروفایلش را ویرایش می‌کرده)، پس اگر وسطِ کار ۴۰۱ بیاید یعنی واقعاً نشستش منقضی شده — و این دقیقاً همان موردی است که تلهٔ سراسری برایش ساخته شد. پس این‌جا هیچ استثنایی نمی‌گذارم؛ می‌گذارم تلهٔ ۴۰۱ی که در http کاشتیم clearUser بزند و کاربر را بیرون کند. یک کدِ وضعیت، حالا چهارمین معنا — و این‌بار درستش این است که سرویس هیچ کاری نکند و بگذارد تله عمل کند.



// خب، پنج سرویس شد و حالا جدول کامل‌تر از همیشه است — و ردیفِ پنجم، مرزِ ظریفِ «هم‌استوری بدونِ هم‌هویتی» را اضافه می‌کند:

// productService	authService	cartService	orderService	userService
// جنسِ عملیات	خواندن	وجودِ نشست	کنشِ خوش‌بینانه	کنشِ برگشت‌ناپذیر	ویرایشِ محتوای هویت
// استور	product	user	cart	order + cart	user (نویسندهٔ دوم)
// ۴۰۱ یعنی	خطا	مهمان / رمزِ غلط	خطا	خطا	منقضی — تله را دست نزن
// به استور دست می‌زند؟	همیشه	همیشه	همیشه	همیشه	گاهی نه (رمز)
// بدنه	JSON	JSON	JSON	JSON + هدرِ سفارشی	JSON یا FormData
// خروجی	void	boolean	boolean	string | null	boolean


// authService و userService روی یک استورند ولی قرینه‌اند — یکی هویت را می‌سازد و می‌کشد، دیگری ویرایشش می‌کند. این جفت، جفتِ cartService/orderService را کامل می‌کند: آن‌جا دیدیم دو عملیاتِ همسایه می‌توانند فلسفهٔ متضاد داشته باشند؛ این‌جا می‌بینیم دو سرویسِ هم‌استور می‌توانند مسئولیتِ کاملاً جدا داشته باشند. در هر دو، مرز از ماهیت آمد، نه از نزدیکیِ ظاهری.

// و باز — پنجمین بار — هر پنج سرویس روی همان یک سنگ ایستاده‌اند که هنوز ننوشته‌امش، و این آخری فهرستِ طلب‌ها را تکمیل کرد. حالا قراردادِ کاملِ http را پنج مصرف‌کننده، خط‌به‌خط، دیکته کرده‌اند:

// union برگرداند ({ ok: true; data } | { ok: false; error }) — هر پنج سرویس.
// credentials: "include" بفرستد — تا کوکیِ HttpOnly برود.
// چهار فعل داشته باشد: get / post / patch / del.
// تلهٔ سراسریِ ۴۰۱ را بزند (clearUser) — که fetchCurrentUser دورش می‌زند و userService تسلیمش می‌شود.
// آرگومانِ { headers } را بپذیرد — برای Idempotency-Key.
// بدنهٔ FormData را تشخیص دهد و Content-Typeِ JSON را رویش تحمیل نکند — تازه‌ترین شرط، از همین فایل.
// پس دیگر http.ts یک صفحهٔ سفید نیست، حتی یک «جای خالیِ اندازه‌گیری‌شده» هم نیست — یک مشخصاتِ کاملِ استخراج‌شده است که پنج فایل امضایش کرده‌اند. هر شرطش از یک خطِ واقعیِ کد آمد، نه از حدس.

// برویم بالاخره services/http.ts را بسازیم؟ این‌بار پنج سرویس بی‌آن کامپایل نمی‌شوند، و شش شرطِ دقیق روی میز است که همه‌شان باید در یک فایل بنشینند. دیگر هیچ بهانه‌ای، هیچ فایلِ مقدم‌تری، هیچ «اول این یکی» نمانده.