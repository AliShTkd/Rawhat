
// src/utils/formatPrice.ts

/**
 * formatPrice = تابعِ خالص. ورودی → خروجی، و هیچ‌چیزِ دیگر.
 * قرینهٔ کاملِ apiClient:
 *   apiClient      → ناخالص‌ترین (سیم، تله، عارضهٔ جانبی).
 *   formatPrice    → خالص‌ترین (بی‌استور، بی‌شبکه، بی‌async، قطعی).
 * قرارداد: سِنتِ صحیح می‌گیرد (نه دلارِ اعشاری)، هرگز throw نمی‌کند،
 * و فرمترِ گران‌قیمت را کش می‌کند چون فهرست‌ها صدها بار صدایش می‌زنند.
 */

export interface PriceOptions {
  currency?: string; // کدِ ISO 4217، پیش‌فرض USD
  locale?: string;   // پیش‌فرض زبانِ مرورگر
}

// کشِ فرمتر — ساختِ Intl.NumberFormat گران است؛ با کلیدِ locale|currency memoize می‌شود.
const cache = new Map<string, Intl.NumberFormat>();

function formatterFor(locale: string, currency: string): Intl.NumberFormat {
  const key = `${locale}|${currency}`;
  let fmt = cache.get(key);
  if (!fmt) {
    fmt = new Intl.NumberFormat(locale, { style: "currency", currency });
    cache.set(key, fmt);
  }
  return fmt;
}

/**
 * cents: کوچک‌ترین واحدِ صحیح از سرور (1999 = ‌۱۹.۹۹ دلار).
 * تقسیم بر ۱۰۰ تنها این‌جا و تنها در لحظهٔ نمایش رخ می‌دهد — پول تا این خط float نمی‌شود.
 */
export function formatPrice(cents: number, opts: PriceOptions = {}): string {
  // سقوطِ نرم: ورودیِ خراب کلِ رندر را سفید نکند.
  if (!Number.isFinite(cents)) return "—";

  const {
    currency = "USD",
    locale = typeof navigator !== "undefined" ? navigator.language : "en-US",
  } = opts;

  try {
    return formatterFor(locale, currency).format(cents / 100);
  } catch {
    // locale/currencyِ نامعتبر هم نباید بترکاند — همان فلسفهٔ apiClient، لبهٔ نمایش.
    return "—";
  }
}











// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — «سِنت، نه دلار» یک انتخابِ محلی نیست، حلقهٔ آخرِ همان زنجیرهٔ اعتماد است: سرور قیمت را صحیح می‌فرستد، apiClient بی‌تفسیر عبورش می‌دهد، cartService بی‌اعتماد به حدسِ خودش نسخهٔ سرور را می‌نشاند، و این‌جا — آخرین ایستگاه پیش از چشمِ کاربر — تازه به float تبدیل می‌شود، آن‌هم فقط برای نمایش. کلِ مسیر، پول را صحیح نگه داشت تا آخرین ممکن‌ترین لحظه. اگر این تابع دلار می‌گرفت، این زنجیره را یک حلقه زودتر پاره می‌کردم.

// کشِ فرمتر — همان درسِ O(1)ِ wishlist، این‌بار در محورِ زمان نه فضا: isIn باید O(1) بود چون هر کارت می‌پرسیدش؛ formatterFor باید کش شود چون هر کارت صدایش می‌زند. الگو یکی است: وقتی می‌دانی صدازننده در یک حلقهٔ داغ است، هزینهٔ ساخت را از حلقه بیرون بکش. یک Mapِ ماژول‌سطح، و ساختِ گران فقط یک‌بار به‌ازای هر جفتِ locale/currency.

// "—"ِ سقوطِ نرم — پارانویای apiClient که به لبهٔ مقابل رسیده: هسته پایین throw را می‌بلعید تا سرویس آرام بماند؛ این تابع بالا throw را می‌بلعد تا رندر آرام بماند. یک قیمتِ خراب باید یک خط را دِفرمه کند، نه کلِ صفحه را. این تنها فایلِ غیرشبکه‌ای است که با هسته یک اصلِ اخلاقی را شریک است: در مرزها، بترس؛ در وسط، آرام باش.

// بی‌async، بی‌استور، بی‌import از پروژه — و این خودش خبر است: پنج سرویس هرکدام از http/store import می‌کردند؛ apiClient از userStore. این فایل از هیچ‌جای پروژه import نمی‌کند — فقط Intlِ استاندارد. یعنی قابلِ تست بدونِ هیچ mockای، قابلِ استفاده در هر جا، و صفر وابستگی به گرافِ ماژول. خلوصِ کامل قیمتش را همین‌جا پس می‌دهد: تستش سه سطر است و هیچ setup نمی‌خواهد.

// چه چیزی این‌جا نیست: تبدیلِ ارز (نرخِ زنده، کارِ سرور یا یک سرویس — این‌جا فقط نمایشِ یک مبلغِ ازپیش‌تعیین‌شده است)، گِردکردنِ تجاری/مالیات (منطقِ دامنه، جای دیگر)، تجزیهٔ رشته به عدد (parsePrice، عملیاتِ وارونه و مسئلهٔ فرمِ ورودی)، و صفرِ اعشارِ اجباری/اختیاری برای ارزهای خاص (اگر لازم شد، از Intl می‌آید نه از دست). این فایل فقط یک عددِ صحیحِ سِنت را به رشتهٔ محلی‌شدهٔ پول تبدیل می‌کند — و بس

// سرویس‌ها تمام شدند، و اولین قدم به بیرونِ آن دنیا فریب‌دهنده است: «formatPrice که دیگر بحث ندارد — یک toFixed(2) و یک علامتِ $ جلویش، سه خط، تمام.» و این‌بار وسوسه از جنسِ دست‌کم‌گرفتن است، نه ادغام. چون این فایل اولین چیزی در کلِ پروژه است که به هیچ‌چیز وصل نیست — نه http، نه استور، نه async، نه Promise. قرینهٔ کاملِ apiClient: آن، ناخالص‌ترین فایلِ لایه بود (سیم، عارضهٔ جانبی، تله)؛ این، خالص‌ترین است (ورودی → خروجی، و هیچ‌چیزِ دیگر). و دقیقاً چون هیچ اتصالی ندارد، تنها منبعِ باگش خودش است — پس همان وسواس، این‌بار به درون چرخانده می‌شود.

// سه تصمیمِ بزرگ که این سه خطِ به‌ظاهر بدیهی را از تلهٔ «توابعِ کمکیِ ساده» جدا می‌کنند:

// تصمیمِ بزرگِ اول — ورودی «سِنت» است (عددِ صحیح)، نه «دلار» (اعشاری)؛ و این نه یک سلیقه، که ادامهٔ همان زنجیرهٔ اعتماد است. یادت هست cartService به حدسِ محلی‌اش بی‌اعتماد بود و setCart(res.data) می‌زد چون سرور قیمت را می‌داند؟ آن قیمت از سرور به‌صورتِ عددِ صحیحِ کوچک‌ترین واحد (سِنت) می‌آید، نه 19.99ِ اعشاری — چون پول هرگز نباید float باشد (0.1 + 0.2 را که یادت هست). پس این تابع 1999 می‌گیرد و "$19.99" می‌دهد؛ تقسیم بر ۱۰۰ تنها در لحظهٔ نمایش رخ می‌دهد و تنها این‌جا. اگر امضا را numberِ دلاری می‌گرفتم، به هر صدازننده اجازه می‌دادم پول را زودتر به float تبدیل کند — و باگِ گِردکردنی می‌کاشتم که تا فاکتور خودش را نشان نمی‌داد.

// تصمیمِ بزرگِ دوم — Intl.NumberFormat می‌سازد، نه رشته‌بازیِ دستی؛ و چون ساختش گران است، کش می‌شود. toFixed(2) و "$"ِ دستی یک باگِ خاموش است: هزارگان‌جداکننده ندارد، محلی‌سازی ندارد (€ بعد از عدد می‌آید نه قبلش، در فارسی جداکننده فرق دارد)، و ارزهای بی‌اعشار (ین) را خراب می‌کند. Intl.NumberFormat همهٔ این‌ها را می‌داند — ولی ساختنِ هر نمونه‌اش گران است، و یک فهرستِ محصولات این تابع را صدها بار در یک رندر صدا می‌زند (همان‌جا که wishlist هم O(1) می‌خواست). پس فرمترها را با کلیدِ locale|currency memoize می‌کنم. این دقیقاً همان الگوی همیشگی است، فقط جابه‌جا: آن‌جا شکلِ استور از الگوی خواندن می‌آمد؛ این‌جا کشِ فرمتر از الگوی فراخوانی می‌آید.

// تصمیمِ بزرگِ سوم — این تابع، مثلِ apiClient، هرگز throw نمی‌کند — ولی به دلیلِ قرینه. apiClient پارانوید بود تا سرویس‌ها آرام بمانند. این‌جا پارانویا از جنسِ دیگری است: یک تابعِ نمایشی که وسطِ رندر throw کند، کلِ کامپوننت را سفید می‌کند — یک قیمتِ nullِ بی‌آزار، کلِ کارتِ محصول را پایین می‌آورد. پس ورودیِ خراب (NaN، null، Infinity) نباید بترکاند؛ باید به یک نمایندهٔ امنِ خالی ("—") سقوطِ نرم کند. سرویس‌ها آرامش را از پایین می‌گرفتند؛ این تابع آرامش را به بالا، به لایهٔ رندر، تحویل می‌دهد.



// و این نقطه، تغییرِ اقلیم است. شش سرویس و یک هسته، همه دربارهٔ زمان بودند: async، Promise، پاسخِ دیرآمده، مسابقه، تلهٔ نشست. این اولین فایلی است که بی‌زمان است — همان ورودی، همیشه همان خروجی، بدونِ استثنا. جدول هم دیگر شکلِ قبل را ندارد، چون ستون‌هایش (استور، ۴۰۱، بدنه) این‌جا همه خالی‌اند:

// لایهٔ سرویس (۶+۱)	formatPrice (اولین util)
// وابسته به زمان؟	بله (async)	نه (قطعی)
// وصل به استور/شبکه؟	همیشه	هیچ‌کدام
// منبعِ باگ	مرزها (شبکه، نشست، مسابقه)	خودِ تابع
// فلسفهٔ throw	هسته می‌بلعد، سرویس آرام	خودش می‌بلعد، رندر آرام
// import از پروژه	همیشه	صفر


// جالب این‌جاست که خالص‌ترین فایلِ پروژه، یک اصلِ اخلاقیِ ناخالص‌ترین فایل را تکرار می‌کند: در مرز بترس، در وسط آرام باش. apiClient این را در محورِ شبکه گفت، formatPrice در محورِ رندر — دو سرِ کاملاً متضادِ معماری، یک قانونِ مشترک. همان درسی که شش سرویس دادند، حالا از بیرونِ لایهٔ سرویس هم صدا می‌زند: مرز از مسئولیت می‌آید، و مسئولیت گاهی «فقط یک عدد را زیبا نشان بده» است — نه کمتر مهم، نه کم‌وسواس‌تر. 🙂







