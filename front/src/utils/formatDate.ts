
// src/utils/formatDate.ts

/**
 * formatDate = خواهرِ formatPrice، ولی نه دوقلوی همسان.
 * مشترک: خالص‌نما، Intl-محور، کش‌دار، سقوطِ نرمِ "—"، هرگز throw.
 * قرینه: تاریخ یک محورِ دوم دارد که قیمت نداشت — «نسبت به حالا» —
 *   و همان محور خلوص را می‌شکند: formatRelative قطعی نیست (ساعت را می‌خواند).
 * قرارداد: رشتهٔ ISOِ UTC می‌گیرد (نه Date)، ناخلوصیِ زمان را به پارامترِ now صریح می‌کند.
 */

export interface DateOptions {
  locale?: string;    // پیش‌فرض زبانِ مرورگر
  timeZone?: string;  // محورِ سومِ کش؛ پیش‌فرض تایم‌زونِ مرورگر
  style?: "short" | "long"; // فشردگیِ نمایشِ مطلق
}

// کشِ فرمتر — کلید اکنون سه‌بُعدی است: locale|timeZone|style (قیمت فقط دو بُعد داشت).
const cache = new Map<string, Intl.DateTimeFormat>();

function formatterFor(locale: string, timeZone: string, style: "short" | "long"): Intl.DateTimeFormat {
  const key = `${locale}|${timeZone}|${style}`;
  let fmt = cache.get(key);
  if (!fmt) {
    fmt = new Intl.DateTimeFormat(locale, {
      timeZone,
      dateStyle: style === "long" ? "long" : "medium",
      timeStyle: style === "long" ? "short" : undefined,
    });
    cache.set(key, fmt);
  }
  return fmt;
}

/** parseِ متمرکز — تنها جایی که رشتهٔ سرور به لحظه تبدیل می‌شود؛ NaN را نرم می‌گیرد. */
function toMs(iso: string): number | null {
  const ms = Date.parse(iso); // ISOِ Zدار قطعی است؛ ابهامِ new Date را دور می‌زنیم.
  return Number.isNaN(ms) ? null : ms;
}

/** نمایشِ مطلق — قطعی و خالص، درست مثلِ formatPrice. */
export function formatDate(iso: string, opts: DateOptions = {}): string {
  const ms = toMs(iso);
  if (ms === null) return "—"; // سقوطِ نرم: تاریخِ خراب کلِ رندر را سفید نکند.

  const {
    locale = typeof navigator !== "undefined" ? navigator.language : "en-US",
    timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone,
    style = "short",
  } = opts;

  try {
    return formatterFor(locale, timeZone, style).format(ms);
  } catch {
    return "—"; // locale/timeZoneِ نامعتبر هم نباید بترکاند — فلسفهٔ لبهٔ نمایش.
  }
}

/**
 * نمایشِ نسبی — «۳ ساعت پیش». این تابع خالص **نیست**:
 * ساعت را می‌خواند، پس همان ورودی در دو زمان دو جواب می‌دهد.
 * ناخلوصی را صریح می‌کنیم: now یک پارامترِ تزریق‌پذیر است تا تست قطعیت را برگرداند.
 */
export function formatRelative(iso: string, now: number = Date.now(), locale?: string): string {
  const ms = toMs(iso);
  if (ms === null) return "—";

  const loc = locale ?? (typeof navigator !== "undefined" ? navigator.language : "en-US");
  const diffSec = Math.round((ms - now) / 1000);

  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ["year", 31536000], ["month", 2592000], ["day", 86400],
    ["hour", 3600], ["minute", 60], ["second", 1],
  ];

  try {
    const rtf = new Intl.RelativeTimeFormat(loc, { numeric: "auto" });
    for (const [unit, secs] of units) {
      if (Math.abs(diffSec) >= secs || unit === "second") {
        return rtf.format(Math.round(diffSec / secs), unit);
      }
    }
    return "—";
  } catch {
    return "—";
  }
}

















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — نزدیک‌ترین کپیِ پروژه بود، ولی یک محورِ دوم همه‌چیز را کج کرد: formatPrice و formatDate تا مرزِ اشتباهِ کپی به هم شبیه‌اند — دقیقاً مثلِ جفتِ cart/wishlist. و درست مثلِ آن جفت، یک تفاوت آن‌ها را قرینه کرد: قیمت یک نقطه در فضاست (مطلق، بی‌زمان)، تاریخ یک نقطه نسبت به حالاست. اگر کورکورانه formatPrice را کپی کرده بودم، formatRelative را هم خالص فرض می‌کردم، Date.now() را مستقیم صدا می‌زدم، و یک تابعِ تست‌ناپذیر می‌ساختم که هر بار اجرا جوابش عوض می‌شد.

// now به‌عنوان پارامتر — همان skipAuthTrap، در محورِ زمان: هرجا یک تابع ناچار از یک وابستگیِ جهانیِ متغیر است (نشستِ ۴۰۱ آن‌جا، ساعتِ سیستم این‌جا)، بهترین کار پنهان‌کردنش نیست، صریح‌کردنش است. skipAuthTrap سیاست را به یک درِ فرارِ آشکار بدل کرد؛ now = Date.now() ناخلوصیِ زمان را به یک ورودیِ قابلِ‌میخ تبدیل می‌کند. ناخلوصیِ صادق، از خلوصِ دروغین بهتر است.

// کلیدِ سه‌بُعدیِ کش — چون تاریخ یک محورِ اجباریِ اضافه دارد: قیمت با locale|currency کامل بود؛ تاریخ بی timeZone ناقص است، چون یک لحظهٔ UTC در هر تایم‌زون یک ساعتِ دیوارِ متفاوت می‌شود. این تفاوت در ذاتِ داده است، نه در سلیقهٔ من: پول جهانی‌ثابت است، زمان جهانی‌نسبی.

// Date.parse نه new Date(...) — و چرا این وسواس مهم است: هر دو در نهایت parse می‌کنند، ولی امضای صریحِ «رشتهٔ ISOِ Zدار» به این معناست که مسیرِ مبهمِ new Date("2024-01-15") (که local/UTC را قاطی می‌کند) هرگز به کد نمی‌رسد. همان حلقهٔ اعتماد: سرور صریح می‌فرستد، من صریح parse می‌کنم، ابهام هیچ‌جا رخنه نمی‌کند.

// چه چیزی این‌جا نیست: محاسبهٔ اختلافِ تقویمی دقیق (روزهای کاری، ماهِ ۲۸/۳۱ روزه، ثانیهٔ کبیسه — کارِ یک کتابخانهٔ تقویم مثلِ Temporal/date-fns، نه این تخمینِ نمایشی)، parseِ ورودیِ کاربر (parseDate، مسئلهٔ فرم و وارونهٔ این)، به‌روزرسانیِ زندهٔ «۳ ساعت پیش» با تیک (کارِ یک هوک/تایمر در کامپوننت، نه این تابعِ لحظه‌ای)، و منطقِ دامنه‌ایِ «آیا منقضی شده؟» (تصمیمِ کسب‌وکار، نه نمایش). این فایل فقط یک لحظهٔ UTC را به رشتهٔ محلی‌شده — مطلق یا نسبی — تبدیل می‌کند.



// دو خواهر، و این‌بار وسوسه از همه شش‌ونیم بارِ قبل صادقانه‌تر به نظر می‌رسد، چون تازه یک الگو را با دستِ خودم ساختم: «formatDate همان formatPrice است با Intl.DateTimeFormat به‌جای NumberFormat — همان کش، همان "—"ِ نرم، همان خلوص، همان امضا. کپی کن، Number را Date کن، تمام.» و این نزدیک‌ترین کپیِ کلِ پروژه است — تا مرزِ یکی‌بودن. و باز نه. formatPrice و formatDate تا یک نقطه مو‌به‌مو یکی‌اند (هر دو خالص‌نما، هر دو کش‌دار، هر دو Intl، هر دو سقوطِ نرم)، ولی درست از جایی که «تاریخ» یک محورِ دومی دارد که «قیمت» هرگز نداشت — نزدیکی به «حالا» — قرینه می‌شوند. و همین یک محور، مثلِ همان سنگِ اولِ دومینو در wishlist، خلوص را هم با خودش می‌برد: تابعی که «۳ ساعت پیش» می‌گوید، دیگر قطعی نیست.

// سه تصمیمِ بزرگ که این خواهرِ به‌ظاهر همسان را از formatPrice جدا می‌کنند:

// تصمیمِ بزرگِ اول — ورودی «رشتهٔ ISO 8601ِ UTC» است، نه Date و نه timestamp؛ و این همان حلقهٔ اعتمادِ formatPrice است، فقط با تلهٔ خطرناک‌تر. formatPrice سِنتِ صحیح گرفت تا پول تا لحظهٔ نمایش float نشود. این‌جا هم‌ارزش دقیقاً همان است: سرور تاریخ را به‌صورتِ رشتهٔ ISOِ UTC می‌فرستد ("2024-01-15T09:30:00Z")، و من همان رشته را می‌گیرم — نه Dateی که یک صدازنندهٔ دیگر ساخته. چرا این‌قدر سخت‌گیر؟ چون new Date() بدنام‌ترین parserِ جاوااسکریپت است: new Date("2024-01-15") را UTC نیمه‌شب می‌خواند، ولی new Date("2024-01-15T09:30") را در تایم‌زونِ محلی — یک ناسازگاریِ خاموش که بسته به کاربر جابه‌جا می‌شود. اگر Date می‌گرفتم، به هر صدازننده اجازه می‌دادم این ابهام را زودتر و پنهانی وارد کند. پس رشتهٔ صریحِ Zدار می‌گیرم و parse را این‌جا، در تنها نقطه‌ای که قاعده‌اش را می‌دانم، انجام می‌دهم.

// تصمیمِ بزرگِ دوم — تاریخ یک محورِ دوم دارد که قیمت نداشت («نسبت به حالا»)، و همین محور خلوص را می‌شکند. formatPrice(1999) همیشه "$19.99" بود — همان ورودی، همیشه همان خروجی، تا ابد. ولی تاریخ دو حالتِ نمایشی دارد: مطلق (۱۵ ژانویه ۲۰۲۴) و نسبی (۳ ساعت پیش). و حالتِ نسبی یک چیزِ تازه به تابع تزریق می‌کند که در کلِ util-ها بی‌سابقه است: خواندنِ ساعتِ سیستم. formatRelative همان ورودی را در دو زمانِ مختلف، دو جوابِ متفاوت می‌دهد. پس این تابع — برخلافِ خواهرِ خالصش — قطعی نیست، و صداقت حکم می‌کند که این ناخلوصی صریح باشد: now را یک پارامترِ تزریق‌پذیر می‌کنم (پیش‌فرض Date.now()) تا تست بتواند زمان را میخ کند و قطعیت را به‌صورتِ محلی بازگرداند. همان درسِ skipAuthTrap: وقتی یک تابع ناچار از ناخلوصی است، آن را به یک پارامتر تبدیل کن، نه یک وابستگیِ پنهان.

// تصمیمِ بزرگِ سوم — کش این‌جا هم هست، ولی کلیدش یک بُعدِ سوم گرفت: تایم‌زون. formatPrice فرمترها را با locale|currency کش کرد. این‌جا همان الگوست، ولی Intl.DateTimeFormat یک محورِ سومِ اجباری دارد که NumberFormat نداشت: تایم‌زونِ نمایش. یک قیمت در همه‌جای دنیا $19.99 است، ولی یک لحظهٔ واحدِ UTC در توکیو و نیویورک دو ساعتِ دیوار متفاوت است. پس کلیدِ کش locale|timeZone|style می‌شود، و تایم‌زون یک انتخابِ صریح است نه یک پیش‌فرضِ نامرئی. باقیِ مکانیک — Mapِ ماژول‌سطح، ساختِ گرانِ یک‌باره، سقوطِ نرمِ "—"، هرگز-throw — مو‌به‌مو از formatPrice به ارث می‌رسد، چون این‌ها واقعاً مشترک‌اند؛ فقط محورها فرق کردند.




// و این ردیف، چیزی را در جدول روشن می‌کند که تا formatPrice پنهان بود: ستونِ «قطعی؟» که فکر می‌کردم برای همهٔ util-ها بله است، همین‌جا در درونِ یک فایل دو نیم می‌شود:

// formatPrice	formatDate (مطلق)	formatRelative (نسبی)
// قطعی؟	بله	بله	نه — ساعت را می‌خواند
// محورهای کش	`locale	currency`	`locale
// ناخلوصیِ صریح	ندارد	ندارد	now پارامتر است
// محورِ دوم	ندارد	ندارد	«نسبت به حالا»
// ارثِ مشترک	—	"—"، Intl، هرگز-throw	همان‌ها


// نکتهٔ ظریف این است: حتی درونِ یک فایلِ util هم دو رفتار می‌تواند کنارِ هم بنشیند — formatDate خواهرِ قطعیِ formatPrice است، ولی formatRelative که در همان فایل زندگی می‌کند، خلوص را کنار می‌گذارد چون داده‌اش یک محورِ بیشتر (زمانِ جاری) حمل می‌کند. همان درسِ کلِ پروژه، این‌بار در کوچک‌ترین مقیاس: دو تابعِ هم‌خانه هم اگر رابطه‌شان با «حقیقت» فرق کند — یکی به عدد، یکی به لحظهٔ گذرا — دو رفتارِ متفاوت می‌گیرند. 🙂