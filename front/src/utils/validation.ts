
// src/utils/validation.ts

/**
 * validation = مرزِ ورود. قرینهٔ کاملِ formatPrice/formatDate:
 *   format*     → مرزِ خروج: دادهٔ موردِاعتمادِ سرور را زیبا بیرون می‌دهد.
 *   validation  → مرزِ ورود: دادهٔ بی‌اعتمادِ کاربر را داوری می‌کند.
 * چون جهت وارونه است، اصول هم وارونه‌اند:
 *   - سقوطِ نرمِ "—" نداریم؛ «نه»‌گفتن کارِ اصلی است، نه عارضه.
 *   - کدِ خطا برمی‌گردانیم نه پیغام (خواهرِ ApiResult): قاعده را می‌دانیم، زبان را نه.
 *   - منبعِ حقیقت نیست؛ UXِ سریع است. صحت را سرور می‌گوید (همان حلقهٔ اعتماد).
 */

export type Validity =
  | { valid: true }
  | { valid: false; code: string }; // مثلِ ApiError.code — نمایش، زبان را می‌سازد.

const OK: Validity = { valid: true };
const fail = (code: string): Validity => ({ valid: false, code });

// یک پیش‌بینیِ میدانی: مقدار را می‌گیرد، داوری می‌دهد. قواعدِ ریز از این جنس‌اند.
export type Rule = (value: string) => Validity;

/* ── قواعدِ ریزِ قابلِ‌ترکیب — چهار «شکرِ» روی یک ایدهٔ داوری ── */

export const required: Rule = (v) =>
  v.trim().length > 0 ? OK : fail("REQUIRED");

export const minLength = (n: number): Rule => (v) =>
  v.length >= n ? OK : fail("TOO_SHORT");

export const maxLength = (n: number): Rule => (v) =>
  v.length <= n ? OK : fail("TOO_LONG");

export const pattern = (re: RegExp, code: string): Rule => (v) =>
  re.test(v) ? OK : fail(code);

/* ── اعتبارسنج‌های مرکب — ساخته‌شده از قواعدِ بالا، نه بازنویسیِ regexِ خام ── */

// regex عمداً محافظه‌کار است: کلاینت فقط «شکلِ آشکارا غلط» را می‌گیرد؛
// یکتایی و وجودِ واقعیِ ایمیل را فقط سرور می‌داند.
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export const validateEmail: Rule = (v) =>
  runField(v, [required, pattern(EMAIL_RE, "EMAIL_INVALID")]);

export const validatePassword: Rule = (v) =>
  runField(v, [required, minLength(8), maxLength(128)]);

/**
 * runField = زنجیرِ قواعد؛ در نخستین شکست می‌ایستد (کوتاه‌مدار).
 * قرینهٔ runField با چهار فعلِ http: هر دو نازک‌اند، منطقِ واقعی یک‌جا جمع است.
 */
export function runField(value: string, rules: Rule[]): Validity {
  for (const rule of rules) {
    const r = rule(value);
    if (!r.valid) return r; // اولین «نه» کافی است؛ کاربر یک خطا در لحظه می‌خواهد نه شش‌تا.
  }
  return OK;
}

/**
 * runForm = داوریِ چند میدان با هم. کلید → کدِ خطا (یا هیچ اگر معتبر).
 * فرم وقتی معتبر است که این نگاشت خالی باشد — الگوی آشنای «خطاها = شیِ کلید-پیام».
 */
export function runForm(
  fields: Record<string, { value: string; rules: Rule[] }>,
): Record<string, string> {
  const errors: Record<string, string> = {};
  for (const key in fields) {
    const { value, rules } = fields[key];
    const r = runField(value, rules);
    if (!r.valid) errors[key] = r.code;
  }
  return errors; // خالی = معتبر. صحتِ نهایی همچنان با سرور است.
}

















// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — «به کلاینت اعتماد نکن» حالا از سمتِ ورودی هم صدا زد: کلِ پروژه یک جهت‌گیریِ اخلاقی داشت که تا حالا فقط از سمتِ خروجی/پاسخ دیده بودم — cartService به سرور تسلیم می‌شد، تلهٔ ۴۰۱ حرفِ سرور را حجت می‌گرفت. حالا همان اصل از سمتِ ورودی هم ظاهر شد: این اعتبارسنجی صحت را تضمین نمی‌کند، فقط بازخوردِ سریع است. اگر این فایل را «منبعِ حقیقتِ اعتبار» می‌پنداشتم، سرور را از داوریِ دوباره معاف می‌کردم و درِ حمله را باز می‌گذاشتم. کلاینت مؤدب است، سرور بی‌رحم.

// کد نه پیغام — همان شکافِ apiClient/http، این‌بار در مرزِ ورود: Validity عمداً خواهرِ ApiResult است. آن‌جا throw به union ریخت تا سرویس آرام بماند؛ این‌جا داوری به union می‌ریزد تا کامپوننت if (r.valid)ِ صاف بنویسد. و کدِ خطا ("EMAIL_INVALID") به‌جای رشتهٔ فارسی یعنی زبان در لایهٔ نمایش می‌ماند — دقیقاً چون منطق واژه‌ها را نمی‌شناسد، فقط قاعده‌ها را.

// کوتاه‌مدار در runField، جمع‌آوری در runForm — دو الگوی متفاوت برای دو مخاطب: یک میدان در لحظه فقط یک خطا می‌خواهد (اولین «نه» و بس)، ولی یک فرم هنگامِ ثبت باید همهٔ میدان‌های خراب را یک‌جا نشان دهد. پس runField در نخستین شکست می‌ایستد، runForm تا آخر می‌رود. تفاوت از مسئولیت می‌آید، نه از سلیقه — همان درسِ همیشگی.

// regexِ محافظه‌کار، عمداً ناقص — و این ضعف نیست، صداقت است: EMAIL_RE فقط «شکلِ آشکارا غلط» را می‌گیرد. regexِ کاملِ RFC 5322 یک هیولاست و باز هم نمی‌تواند بگوید ایمیل واقعاً وجود دارد. پس عمداً کم‌کار می‌مانم: کلاینت غلطِ فاحش را زود می‌گیرد، سرور (و ایمیلِ تأیید) بقیه را. تظاهر به دانستنِ چیزی که فقط سرور می‌داند، همان دروغی است که کلِ پروژه از آن پرهیخت.

// چه چیزی این‌جا نیست: اعتبارسنجیِ async (یکتاییِ ایمیل، موجودیِ کوپن — رفت‌وبرگشتِ شبکه، کارِ یک سرویس، نه این تابعِ همگام و خالص)، پیغامِ محلی‌شده (کارِ لایهٔ i18n روی کد، درست مثلِ http روی request)، sanitization/escapeِ خروجی (مسئلهٔ امنیتیِ رندر، جهتِ مقابل)، و طرح‌وارهٔ کاملِ اجباری مثلِ zod (اگر گرافِ اعتبار پیچیده شد، شاید — ولی این‌جا فقط میدان‌های ساده است). این فایل فقط ورودیِ خامِ رشته‌ای را به یک داوریِ ساختارمند و کددار تبدیل می‌کند، و صحتِ نهایی را به سرور وامی‌گذارد.



// وارونه‌سازیِ جریان — و این‌بار وسوسه از جنسِ جهت است، نه شباهت. دو فایلِ قبل مرا در یک شیار انداخته‌اند: «validation هم یک util است مثلِ آن دو خواهر — خالص، قطعی، یک Map برای کشِ regex، یک "—"ی نرم برای ورودیِ خراب، امضای (value, opts) => string. سومین قلوی همان خانواده.» و این نزدیک است، ولی از یک جای عمیق غلط است: formatPrice و formatDate هر دو مرزِ خروج بودند — دادهٔ مورد‌اعتمادِ سرور را می‌گرفتند و زیبا بیرون می‌دادند. validation مرزِ مقابل است — مرزِ ورود — و دادهٔ بی‌اعتمادِ کاربر را می‌گیرد تا داوری کند. و درست از همین وارونگیِ جهت، هر اصلی که در آن دو خواهر ساختم این‌جا پشت‌ورو می‌شود.

// سه تصمیمِ بزرگ که این خواهرخواندهٔ ظاهراً‌همسان را قرینه می‌کنند:

// تصمیمِ بزرگِ اول — جهت وارونه شد، پس فلسفهٔ throm/سقوطِ نرم هم وارونه می‌شود: این‌جا «نه»‌گفتن کارِ اصلی است، نه عارضه. در formatPrice، رشتهٔ "—" یک سقوطِ نرم بود — «ورودی خراب بود، ولی رندر را سفید نکن.» آن‌جا خطای ورودی یک اتفاقِ نادر و شرم‌آور بود که باید بی‌سروصدا قورت می‌شد. این‌جا دقیقاً برعکس: ورودیِ نامعتبر رخدادِ اصلی و موردِ انتظار است. یک تابعِ اعتبارسنجی که ورودیِ بد را نرم و خاموش بپذیرد، کلِ کارش را انجام نداده. پس این‌جا سقوطِ نرمی وجود ندارد؛ برعکس، تابع باید بلند و ساختارمند بگوید «نه، و به این دلیل». همان محورِ اخلاقیِ «در مرز بترس» که apiClient و formatPrice مشترک داشتند، این‌جا هست — ولی چون این مرزِ ورود است، ترس شکلِ رد کردن می‌گیرد، نه شکلِ بلعیدن.

// تصمیمِ بزرگِ دوم — کد برمی‌گرداند، نه پیغام؛ و نه boolean. این دقیقاً همان شکافِ apiClient/http است. وسوسه این است که validateEmail مستقیم "ایمیل نامعتبر است" برگرداند، یا بدتر، فقط false. هر دو غلط‌اند. falseِ لخت اطلاعات را دور می‌ریزد — کامپوننت نمی‌داند کدام قاعده شکست تا پیغامِ درست را نشان دهد. و رشتهٔ فارسیِ سرراست، مسئولیتِ زبان را به دلِ منطق می‌کشد — همان اشتباهی که در apiClient نکردم: هسته request را می‌دانست، http واژه‌ها را. این‌جا هم عیناً همان: اعتبارسنج قاعدهٔ شکسته را می‌داند ("EMAIL_INVALID")، لایهٔ نمایش زبان را. پس خروجی یک union است — { valid: true } | { valid: false; code } — درست خواهرِ ApiResult. آن‌جا throw به union ریخت؛ این‌جا داوری به union می‌ریزد. کدِ خطا، همان ApiError.code است، فقط در مرزِ ورود.

// تصمیمِ بزرگِ سوم — قواعدِ ریز compose می‌شوند، و مهم‌تر: این اعتبارسنجی منبعِ حقیقت نیست، UX است. درست مثلِ چهار فعلِ http که شکرِ نازکِ روی یک request بودند، این‌جا هم اعتبارسنج‌های میدانی از پیش‌بینی‌های ریز (required, minLength, pattern) ساخته می‌شوند و یک runField آن‌ها را زنجیر می‌کند. ولی تصمیمِ عمیق‌تر، همان درسِ تکرارشوندهٔ کلِ پروژه است: به کلاینت اعتماد نکن. یادت هست cartService به حدسِ محلی‌اش بی‌اعتماد بود و نسخهٔ سرور را می‌نشاند؟ یادت هست تلهٔ ۴۰۱ سرور بود که می‌گفت نشست مرده؟ این اعتبارسنجیِ سمتِ کلاینت صحت را تضمین نمی‌کند — فقط بازخوردِ سریع می‌دهد تا کاربر منتظرِ رفت‌وبرگشتِ شبکه نماند. یکتاییِ ایمیل، موجودیِ انبار، درستیِ کوپن — همه فقط سرور می‌داند. پس این فایل عمداً کارهایی را که نمی‌تواند صادقانه انجام دهد، انجام نمی‌دهد؛ فقط قواعدِ نحوی و محلیِ قابل‌داوری را می‌سنجد.



// و این ردیف، جدول را حولِ محوری می‌چرخاند که تا حالا اصلاً ستون نبود — جهتِ داده. دو خواهرِ قبل هر دو رو به بیرون بودند؛ این اولین فایلی است که رو به درون است، و همین جهت هر خانه را قرینه می‌کند:

// format* (خروج)	validation (ورود)
// جهتِ داده	سرور → کاربر	کاربر → سرور
// اعتمادِ به ورودی	دادهٔ موردِاعتماد	دادهٔ بی‌اعتماد
// رفتار با خرابی	سقوطِ نرمِ "—"	رد کردنِ بلند و کددار
// «نه»‌گفتن	عارضهٔ نادرِ شرم‌آور	کارِ اصلی و موردِ انتظار
// منبعِ حقیقت؟	سرور (فقط نمایش)	سرور (فقط UXِ سریع)
// ارثِ union	ApiResult را وام داد	Validity هم‌خانوادهٔ آن


// نکتهٔ ظریفِ این ایستگاه این است: دو فایلِ util که فکر می‌کردم یک خانواده‌اند (خالص، Intl، کش، "—")، در واقع فقط یک سرِ یک محورند — سرِ خروج. validation سرِ دیگرِ همان محور است، و با اینکه در پوشهٔ utils کنارشان می‌نشیند، آینهٔ آن‌هاست نه ادامه‌شان. همان درسِ اولِ کلِ پروژه، حالا در آخرین شکلش: همسایگیِ پوشه‌ای دلیلِ هم‌خانوادگی نیست؛ مسئولیت جهت دارد، و جهت، خویشاوندی را تعیین می‌کند — نه محلِ سکونت.