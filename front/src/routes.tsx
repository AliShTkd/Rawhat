/**
 * routes = توپولوژی، نه فرماندهی. اولین .tsx: پلِ منطقِ نادیدنی به صفحهٔ دیدنی.
 * مسئولیتِ تک‌کلمه‌ای: کدام URL → کدام صفحه، در کدام قاب، پشتِ کدام در.
 * چه چیزی این‌جا نیست: هیچ fetch، هیچ قاعدهٔ کسب‌وکار، هیچ تصمیم — فقط نقشه.
 * سه ارثِ صریح:
 *   - path از ROUTES می‌آید (constants)، نه رشتهٔ خام — تک‌منبعِ حقیقت.
 *   - RequireAuth مثلِ validation: UXِ سریع، نه امنیت. حقیقت با ۴۰۱ سرور است.
 *   - مرزِ مسیر = مرزِ lazy؛ Suspense/errorElement = همان "—"ِ formatPrice در مقیاسِ صفحه.
 */

import { lazy, Suspense } from "react";
import { createBrowserRouter, Navigate, Outlet, useLocation } from "react-router-dom";
import { ROUTES } from "./constants";
import { useSession } from "./hooks/useSession"; // نشست را می‌خواند، خودش داوری نمی‌کند.

// هر صفحه lazy — هزینهٔ باندل فقط وقتِ لازم پرداخت می‌شود (فلسفهٔ formatterFor).
const HomePage      = lazy(() => import("./pages/HomePage"));
const ProductsPage  = lazy(() => import("./pages/ProductsPage"));
const CartPage      = lazy(() => import("./pages/CartPage"));
const CheckoutPage  = lazy(() => import("./pages/CheckoutPage"));
const OrdersPage    = lazy(() => import("./pages/OrdersPage"));
const LoginPage     = lazy(() => import("./pages/LoginPage"));

// قابِ مشترک: چیدمان + مرزِ Suspense. سقوطِ نرمِ «در حالِ آمدن».
function AppLayout() {
  return (
    <Suspense fallback={<PageSpinner />}>
      <Outlet />
    </Suspense>
  );
}

/**
 * RequireAuth = نگهبانِ مؤدب، نه دیوار. مثلِ validation: بازخوردِ سریع، نه صحت.
 * دادهٔ واقعی را ۴۰۱ سرور (تلهٔ apiClient) نگه می‌دارد؛ این فقط ریدایرکتِ زیباست.
 */
function RequireAuth() {
  const { user, loading } = useSession();
  const location = useLocation();

  if (loading) return <PageSpinner />;        // هنوز نمی‌دانیم؛ قضاوتِ زودرس نکن.
  if (!user) {
    // from را نگه می‌داریم تا پس از ورود، کاربر به‌جایی که می‌خواست برگردد.
    return <Navigate to={ROUTES.login} state={{ from: location }} replace />;
  }
  return <Outlet />;
}

export const router = createBrowserRouter([
  {
    element: <AppLayout />,
    errorElement: <RouteError />, // مرزِ خطا: یک زیردرختِ خراب، ریشه را سفید نکند.
    children: [
      // ── مسیرهای عمومی ──
      { path: ROUTES.home,     element: <HomePage /> },
      { path: ROUTES.products, element: <ProductsPage /> },
      { path: ROUTES.cart,     element: <CartPage /> },
      { path: ROUTES.login,    element: <LoginPage /> },

      // ── پشتِ در: فقط با نشست ──
      {
        element: <RequireAuth />,
        children: [
          { path: ROUTES.checkout, element: <CheckoutPage /> },
          { path: ROUTES.orders,   element: <OrdersPage /> },
        ],
      },

      // ناشناخته → خانه. نه throw، نه صفحهٔ سفید (همان فلسفهٔ سقوطِ نرم).
      { path: "*", element: <Navigate to={ROUTES.home} replace /> },
    ],
  },
]);



























// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — «توپولوژی، نه فرماندهی»؛ این فایل هیچ فعلی از خودش ندارد: درست مثلِ constants که وسوسهٔ زباله‌دان‌شدن داشت، routes وسوسهٔ «کمی از هر کاری» دارد — یک fetch این‌جا، یک شرطِ نقش آن‌جا. هر دو یک بیماری‌اند. مرزِ این فایل تیز است: گره‌زدنِ URL به صفحه، و بس. هر منطقی که به این‌جا نشت کند (بارگذاریِ داده، قاعدهٔ کسب‌وکار، تصمیمِ نقش) از جای درستش — سرویس، هوک، صفحه — دزدیده شده.

// RequireAuth امنیت نیست، UX است — همان درسِ validation در محورِ ناوبری: این ظریف‌ترین تلهٔ فایل است. نگهبانِ مسیر فقط از نشان‌دادنِ صفحه‌ای که قرار است با ۴۰۱ بترکد جلوگیری می‌کند؛ محافظتِ واقعیِ داده با تلهٔ ۴۰۱ در apiClient و داوریِ سرور است. اگر این را دیوارِ امنیتی بپندارم، سرور را از کار معاف می‌کنم و همان اشتباهی را می‌کنم که validation هشدارش را داد: کلاینت مؤدب، سرور بی‌رحم.

// ROUTES نه رشتهٔ خام — این‌جا مصرف‌کنندهٔ تصمیمِ constants است: اگر path="/cart" را دوباره خام بنویسم، کلِ فلسفهٔ «تک‌منبعِ حقیقتِ مسیر» را که در constants ساختم می‌شکنم. این فایل صاحبِ هیچ مسیری نیست؛ فقط از ROUTES وام می‌گیرد. همان یک‌طرفگیِ «یک نویسنده، بقیه خواننده» — constants می‌نویسد، routes می‌خواند.

// مرزِ مسیر = مرزِ lazy = مرزِ سقوطِ نرم — سه‌گانه‌ای که با هم می‌آیند: هر جداییِ صفحه سه چیز را هم‌زمان می‌طلبد: lazy (هزینهٔ به‌موقع، فلسفهٔ formatterFor)، Suspense (سقوطِ نرمِ انتظار)، و errorElement (سقوطِ نرمِ فروپاشی). این‌ها جدا نیستند؛ لحظه‌ای که یک صفحه را lazy می‌کنی، دو حالتِ تازه (در حالِ آمدن / نیامد) می‌سازی که هر کدام یک "—"ی سطحِ‌صفحه لازم دارند — همان درسِ formatPrice، بزرگ‌شده.

// چه چیزی این‌جا نیست: بارگذاریِ داده (loaderهای react-router یا fetch در صفحه — نه این نقشه)، منطقِ کسب‌وکارِ ناوبری («اگر سبد خالی است checkout نده» — تصمیمِ دامنه، جای صفحه/سرویس)، تعریفِ رشتهٔ مسیر (constants)، محافظتِ واقعیِ داده (سرور + تلهٔ ۴۰۱)، و کامپوننت‌های صفحه (هر کدام فایلِ خودش؛ این‌جا فقط lazyشان می‌کنم). این فایل فقط URLها را به صفحه‌ها، در قاب و پشتِ در، گره می‌زند.



// نخستین .tsx — و این وسوسه از جنسِ تازه‌ای است که تا حالا نبود: تا این‌جا هر فایل یا رفتار بود (apiClient, validation) یا داده (constants)، ولی هیچ‌کدام دنیای دیده‌نشدنیِ منطق را به دنیای دیدنیِ صفحه وصل نمی‌کرد. و وسوسه این است: «routes.tsx قلبِ برنامه است — این‌جا که همهٔ صفحه‌ها به هم می‌رسند، پس بگذار کمی منطق هم این‌جا بنشیند: یک useEffect که کاربر را چک کند، یک fetchِ کوچک قبلِ ورود به صفحه، یک شرطِ نقش این‌جا، یک redirectِ آن‌جا. بالاخره این‌جا نقشهٔ همه‌چیز است.» و این همان تلهٔ constants است در آینه: constants وسوسه می‌شد همه‌چیز را بپذیرد؛ routes وسوسه می‌شود کمی از هر کاری بکند. و هر دو یک بیماری‌اند — فایلی که مسئولیتش را گم می‌کند. routes.tsx یک مسئولیتِ تک‌کلمه‌ای دارد: توپولوژی. کدام URL به کدام صفحه، در کدام قاب، پشتِ کدام در. همین. نه یک fetch، نه یک قاعدهٔ کسب‌وکار، نه یک تصمیم — فقط نقشه‌ای از سرزمین، که خودش هیچ‌جا سفر نمی‌کند.

// سه تصمیمِ بزرگ که این نقشه را از تلهٔ «مرکزِ فرماندهی» جدا می‌کنند:

// تصمیمِ بزرگِ اول — این فایل ترکیب می‌کند، تعریف نمی‌کند؛ و مسیرها را از constants می‌خواند نه از رشتهٔ خام. constants.ts را به یاد بیاور: ROUTES.cart = "/cart" را آن‌جا یک‌بار نوشتم تا router و لینک‌ها و ریدایرکت‌ها از یک منبع بنوشند. حالا این‌جا اولین مشتریِ بزرگِ آن تصمیم است. اگر این‌جا path="/cart" را دوباره به‌صورتِ رشتهٔ خام بنویسم، همان واگراییِ خاموش را کاشته‌ام که کلِ ROUTES برای دفعش ساخته شد. پس هر path از ROUTES می‌آید، و این فایل صاحبِ هیچ رشتهٔ مسیری نیست — فقط آن‌ها را به کامپوننت گره می‌زند. routes.tsx تعریف‌کننده نیست، بافنده است: تارها (ROUTES) و پودها (صفحه‌ها) از جای دیگر می‌آیند، این‌جا فقط به هم می‌بافند.

// تصمیمِ بزرگِ دوم — نگهبانِ مسیر هست، ولی او هم مثلِ validation منبعِ حقیقت نیست؛ UXِ سریع است، نه امنیت. وسوسه این است که RequireAuth را یک دیوارِ امنیتی بپندارم. ولی این دقیقاً همان درسِ validation است، حالا در محورِ ناوبری: اعتبارسنجیِ سمتِ کلاینت صحت را تضمین نمی‌کرد، فقط بازخوردِ سریع می‌داد. نگهبانِ مسیر هم همان است — اگر کاربرِ بدون‌نشست به /checkout برود، RequireAuth او را به /login می‌فرستد نه چون داده را محافظت می‌کند، بلکه چون نشان‌دادنِ یک صفحهٔ خالی که بعد با ۴۰۱ می‌ترکد، تجربهٔ بدی است. دادهٔ واقعی همچنان با همان تلهٔ ۴۰۱ در apiClient محافظت می‌شود — سرور است که «نه» می‌گوید. اگر این نگهبان را حصارِ امنیتی می‌پنداشتم، سرور را از داوری معاف می‌کردم و همان درِ حمله را باز می‌گذاشتم. نگهبانِ مسیر مؤدب است؛ سرور بی‌رحم. پس او فقط ریدایرکتِ زیبا می‌کند، و حتی مقصدِ بازگشت (from) را نگه می‌دارد تا پس از ورود کاربر به‌جایی که می‌خواست برگردد.

// تصمیمِ بزرگِ سوم — مرزِ مسیر همان مرزِ code-split است، و هر مرز دو سقوطِ نرم می‌خواهد: Suspense برای انتظار، errorElement برای فروپاشی. یک صفحه به‌ندرت همان لحظه لازم است؛ کاربرِ صفحهٔ محصولات شاید هرگز به /checkout نرود. پس هر صفحه lazy می‌شود — همان فلسفهٔ formatterFor که هزینه را فقط وقتِ لازم پرداخت، این‌بار در محورِ باندل نه محاسبه. ولی lazy یعنی دو حالتِ تازه که صفحهٔ همیشه‌حاضر نداشت: در حالِ آمدن و نیامد. و این‌جا همان درسِ "—"ی formatPrice برمی‌گردد، ولی در مقیاسِ کلِ صفحه: Suspense یک fallback می‌دهد تا انتظار سفیدیِ ترسناک نباشد، و errorElement یک مرزِ خطا می‌کشد تا فروپاشیِ یک صفحه کلِ برنامه را سفید نکند. همان «در لبهٔ نمایش بترس» که formatPrice تک‌سلولی رعایت کرد، این‌جا در سطحِ درختِ کامل: یک زیردرختِ خراب، ریشه را با خود نمی‌برد.


// و این ایستگاه، جدول را حولِ محوری می‌چرخاند که تا حالا اصلاً وجود نداشت، چون همهٔ فایل‌های قبل در یک سمتِ پرده بودند — سمتِ منطق. routes.tsx اولین فایلی است که روی خودِ پرده می‌ایستد: پلی که منطقِ نادیدنی را به صفحهٔ دیدنی وصل می‌کند، بی‌آنکه خودش هیچ‌کدام باشد.

// فایل‌های تا این‌جا (منطق/داده)	routes.tsx (پل)
// جنس	رفتار یا داده	توپولوژی — نقشهٔ اتصال
// فعلِ خودش	دارد (می‌فرستد/داوری) یا هیچ (constants)	ندارد — فقط گره می‌زند
// نویسنده/خواننده	متغیر	خوانندهٔ ROUTES، ترکیب‌کنندهٔ صفحه‌ها
// سقوطِ نرم	تک‌سلولی ("—")	سطحِ‌صفحه (Suspense/errorElement)
// نگهبانی	validation ورودی را داوری کرد	RequireAuth: همان درس، UX نه امنیت
// منبعِ حقیقتِ دسترسی	—	سرور (۴۰۱)، نه این نگهبان


// نکتهٔ ظریفِ این ایستگاه این است: routes.tsx قدرتمندترین‌فایلِ به‌ظاهر پروژه است — بالاخره «همه‌چیز از این‌جا می‌گذرد» — ولی درست به همین دلیل باید کم‌قدرت‌ترین در عمل باشد. هرچه یک فایل بیشتر در مرکزِ عبورومرور باشد، وسوسهٔ انباشتِ منطق در آن بیشتر، و فاجعهٔ آن انباشت هم بزرگ‌تر. constants چون بی‌فعل بود می‌توانست بی‌صدا بپوسد؛ routes چون پرعبور است می‌تواند پرصدا بترکد — به قبضهٔ کنترلی بدل شود که هر تصمیمِ برنامه از دلش رد می‌شود. همان درسِ کلِ پروژه، در پرترافیک‌ترین شکلش: نقشه نباید جای مقصد را بگیرد؛ فایلی که همه‌چیز از آن می‌گذرد باید کم‌ترین چیز را نگه دارد — وگرنه از پلی برای عبور، به گلوگاهی برای خفگی بدل می‌شود