

// src/stores/userStore.ts
import { create } from "zustand";
import type { User } from "../types/user";
import type { AsyncState, ApiError } from "../types/api";

/**
 * وضعیتِ احرازِ هویت — ماشینِ حالتِ صریح.
 * `unknown` حیاتی است: چون توکن در کوکیِ httpOnly است و JS نمی‌خواندش،
 * موقعِ بوتِ اپ نمی‌دانیم کاربر کیست تا یک‌بار از سرور بپرسیم.
 * UI با این بینِ «مهمانِ قطعی» و «هنوز معلوم نیست» فرق می‌گذارد.
 */
export type AuthStatus = "unknown" | "authenticated" | "anonymous";

/**
 * شکلِ استورِ کاربر = هویت + وضعیتِ احراز + وضعیتِ عملیاتِ ناهمگام + کنش‌ها.
 * هیچ توکنی این‌جا نیست — عمدی. کوکیِ httpOnly حرفِ آخر را می‌زند.
 */
interface UserStore {
  /** پروفایلِ کاربرِ فعلی، یا null اگر مهمان/نامعلوم. */
  user: User | null;
  /** ماشینِ حالتِ احراز؛ از `unknown` شروع می‌شود. */
  status: AuthStatus;
  /**
   * وضعیتِ آخرین عملیاتِ احراز (login/register/logout).
   * جدا از `status`: این «آیا درخواست در جریان/خطا خورد» را می‌گوید،
   * آن یکی «کاربر در نهایت کیست». خطای فرم این‌جا می‌نشیند.
   */
  auth: AsyncState<User>;

  // — گذارهای موفق (سرویس پس از پاسخِ سرور صدا می‌زند) —
  /** نشستنِ کاربرِ احرازشده — پس از login/register/me موفق. */
  setUser: (user: User) => void;
  /** پاک‌کردنِ هویت — پس از logout یا ۴۰۱. کاربر قطعاً مهمان است. */
  clearUser: () => void;
  /** نتیجهٔ قطعیِ «مهمان بودن» پس از پرسشِ سرور (me برگشت خالی). */
  setAnonymous: () => void;

  // — وضعیتِ عملیات —
  /** شروعِ یک عملیاتِ احراز — دکمه را به حالتِ loading می‌برد. */
  setAuthLoading: () => void;
  /** خطای عملیاتِ احراز — fieldErrors برای زیرِ ورودی‌های فرم. */
  setAuthError: (error: ApiError) => void;
}

export const useUserStore = create<UserStore>((set) => ({
  user: null,
  status: "unknown",
  auth: { status: "idle" },

  setUser: (user) =>
    set({
      user,
      status: "authenticated",
      auth: { status: "success", data: user },
    }),

  clearUser: () =>
    // خروج یا ۴۰۱: هویت پاک، ولی این یک خطا نیست — auth به idle برمی‌گردد.
    set({
      user: null,
      status: "anonymous",
      auth: { status: "idle" },
    }),

  setAnonymous: () =>
    // پاسخِ قطعیِ سرور: کاربر مهمان است. `unknown` → `anonymous`.
    set({ user: null, status: "anonymous" }),

  setAuthLoading: () =>
    set((state) => ({ auth: { ...state.auth, status: "loading", error: undefined } })),

  setAuthError: (error) =>
    // خطای login/register: هویت دست‌نخورده (شاید قبلاً لاگین بوده)،
    // فقط عملیات شکست خورد. fieldErrors می‌رود زیرِ ورودی‌ها.
    set((state) => ({ auth: { status: "error", data: state.auth.data, error } })),
}));














// نکاتِ مهمِ کوتاه:

// مهم‌ترین تصمیم — دو ماشینِ حالتِ جدا: status و auth: این ظریف‌ترین انتخابِ فایل است و شاید اولش عجیب به‌نظر برسد چرا دو تا. status می‌گوید کاربر در نهایت کیست (unknown/authenticated/anonymous)؛ auth می‌گوید آخرین عملیات در چه حالی است (idle/loading/error). چرا جدا؟ چون این‌ها هم‌زمان و مستقل تغییر می‌کنند: کاربری که قبلاً authenticated است می‌تواند یک عملیاتِ loading داشته باشد (مثلاً ویرایشِ پروفایل)، یا یک login که error خورد نباید هویتِ قبلی را پاک کند. اگر یکی‌شان می‌کردم، «دکمه در حالِ لود» و «کاربر کیست» به‌هم گره می‌خوردند و حالت‌های نامعتبر می‌ساختند.

// unknown تنها راهِ درستِ بوتِ اپ است: چون تصمیمِ کوکیِ httpOnly توکن را از دسترسِ JS بیرون برد، اپ در لحظهٔ اول واقعاً نمی‌داند کاربر کیست. اگر از anonymous شروع می‌کردم، یک کاربرِ لاگین برای یک لحظه «مهمان» دیده می‌شد و ممکن بود به صفحهٔ ورود پرت شود — یک چشمک‌زدنِ زشت. unknown به UI می‌گوید «صبر کن، دارم می‌پرسم» تا me() جواب بدهد و به authenticated یا anonymous قطعی برسیم. این همان چیزی است که آن پنج صفحهٔ auth برای «محافظتِ مسیر» لازم دارند.

// clearUser در برابرِ setAuthError — تفاوتِ «خروج» و «شکستِ ورود»: هر دو خطا به‌نظر می‌رسند ولی کاملاً متفاوت‌اند. clearUser (خروج یا ۴۰۱) می‌گوید «هویت رفت، ولی این طبیعی است» — پس auth به idle برمی‌گردد، نه error. setAuthError (رمزِ اشتباه) می‌گوید «عملیات شکست خورد، ولی هویتِ قبلی — اگر بود — دست‌نخورده» — پس dataی قبلی حفظ می‌شود. این تفکیک جلوی این باگ را می‌گیرد که یک رمزِ اشتباه، کاربری را که قبلاً لاگین بوده از سیستم بیندازد.

// fieldErrors بالاخره به مقصد رسید: یادت هست در api.ts گفتم fieldErrors «پلِ مستقیم به فرم‌هاست» و در user.ts تایپ‌های LoginCredentials/RegisterInput را ساختیم؟ این‌جا حلقه بسته می‌شود: setAuthError یک ApiError می‌گیرد که fieldErrorsاش کلیدهایش دقیقاً نامِ فیلدهای همان تایپ‌های ورودی است — پس فرمِ ورود می‌تواند «رمز اشتباه است» را مستقیم زیرِ فیلدِ رمز بگذارد.

// چه چیزی این‌جا نیست (عمدی): خودِ login/register/logout/me که با سرور حرف می‌زنند (کارِ services/auth.ts؛ استور فقط گذارهای state است)، مدیریتِ کوکی و refresh-token (زیرساختِ services/http)، و محافظتِ مسیر/ریدایرکت (کارِ کامپوننتِ ProtectedRoute که این status را می‌خواند). این فایل فقط هویت و گذارهایش است.



// رسیدیم به stores/userStore.ts — و این فایل همان تصمیمی را که سه بار به تعویق انداختیم بالاخره مجبورمان می‌کند بگیریم: «کوکی یا توکن؟» نمی‌شود یک استورِ احراز هویت نوشت و از کنارش رد شد؛ خودِ شکلِ state به این جواب بند است. پس اول تصمیم را صریح می‌گیرم، بعد کد — چون این‌بار تصمیم ساختارِ فایل را عوض می‌کند، نه فقط یک جزئیات را.

// تصمیمِ بزرگ — کوکیِ httpOnly، نه توکن در state/localStorage. توکن (session/refresh) در یک کوکیِ httpOnly می‌نشیند که جاوااسکریپت اصلاً نمی‌تواند بخواندش — یعنی در برابرِ XSS امن است. نتیجهٔ مستقیمش برای این فایل: استور هیچ توکنی نگه نمی‌دارد. فقط پروفایلِ کاربر و وضعیتِ احراز را نگه می‌دارد. این دقیقاً همان انضباطی است که در user.ts گذاشتیم — User عمداً توکن را بیرون گذاشت — و حالا آن تصمیمِ تایپ، این‌جا خودش را به‌شکلِ ساختارِ استور نشان می‌دهد. مرورگر کوکی را خودکار با هر درخواست می‌فرستد؛ کلاینت فقط می‌پرسد «من کی هستم؟» و سرور از روی کوکی جواب می‌دهد.

// پیامدِ دوم — مفهومِ «هنوز نمی‌دانم». چون توکن در JS نیست، موقعِ بالا آمدنِ اپ نمی‌دانیم کاربر لاگین است یا نه تا وقتی یک‌بار از سرور بپرسیم (me()). پس علاوه بر authenticated/anonymous، یک حالتِ سومِ صریح لازم داریم: unknown (هنوز نپرسیده‌ایم) — تا UI بینِ «مطمئناً مهمان» و «هنوز معلوم نیست، اسپینر نشان بده» فرق بگذارد. این ظریف‌ترین بخشِ فایل است.





// خب، این فایل قرینهٔ دقیقِ cartStore است ولی یک قدم بالغ‌تر، و یک الگو را قطعی کرد: استورهای ما همه یک شکل دارند — داده + AsyncState + کنش‌های گذار، و هیچ‌کدام fetch نمی‌زنند. حالا دو استور کنارِ هم داریم که همین را ثابت می‌کنند:

// استور	دادهٔ اصلی	ماشینِ حالتِ خاص	نیمهٔ شبکه‌ایِ منتظر
// cartStore ✅	Cart	خوش‌بینانه/آشتی	services/cart.ts
// userStore ✅	User | null	unknown/auth/anon	services/auth.ts
// و مهم‌تر: تصمیمِ معلقِ «کوکی یا توکن» بالاخره بسته شد — httpOnly، بی‌توکن در state. این یک بدهیِ تصمیمی بود که سه فایل ازش فرار کرده بودند؛ حالا رسمی است و services/auth دیگر بلاتکلیف نیست.

// ولی همان الگوی جدول یک چیزِ آزاردهنده را هم رو می‌کند: دو استور ساختیم که هیچ‌کدام هنوز نمی‌توانند با سرور حرف بزنند. نیمهٔ شبکه‌ایِ هر دو خالی است، و هر دو به یک چیزِ مشترک بند‌ند که هنوز نساخته‌ایم — یک لایهٔ http پایه.

// پس سه مسیرِ منطقی، که این‌بار وزن‌شان عوض شده:

// services/http.ts (پیشنهادِ اول حالا) — پایهٔ مشترکِ هر دو سرویسِ بعدی: کوکی را خودکار می‌فرستد (credentials: "include")، پاسخ را به ApiSuccess/ApiError تبدیل می‌کند، و ۴۰۱ را به clearUser وصل می‌کند. بدونش، نه services/cart ممکن است نه services/auth. حالا که دو استور منتظرش‌اند، این گلوگاه است.
// utils/money.ts — هنوز آن حلقهٔ مفقودهٔ نمایشِ subtotal است؛ کوچک و کاملاً تست‌پذیر، بی‌نیاز به هیچ تصمیم.
// services/auth.ts — که حالا تصمیمش باز شده، ولی به http.ts بند است.
// نظرم؟ این‌بار services/http.ts — چون تازه دو استور ساختیم که هر دو به یک لایهٔ شبکهٔ مشترک بند شدند، و آن تصمیمِ کوکی که همین الان گرفتیم دقیقاً باید آن‌جا پیاده شود (credentials: "include" و تله‌ی ۴۰۱). ساختنش الان یعنی دو سرویسِ بعدی فقط رویش سوار می‌شوند. ولی اگر بخواهی یک چیزِ کوچک و تمام‌شده و تست‌پذیر ببینی، utils/money.ts هنوز سرِ جایش است. کدام